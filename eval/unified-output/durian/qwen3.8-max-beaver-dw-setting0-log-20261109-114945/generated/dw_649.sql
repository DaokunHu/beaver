WITH Subq1 AS (
    SELECT t2.SUBJECT_CODE,
           t2.SUBJECT_CODE_DESC,
           t1.DEPARTMENT_NAME,
           t2.SCHOOL_NAME,
           t0.SUBJECT_TITLE,
           t0.NUM_ENROLLED_STUDENTS,
           ROW_NUMBER() OVER (PARTITION BY t1.DEPARTMENT_NAME ORDER BY t2.SUBJECT_CODE) AS window_column
    FROM TIP_SUBJECT_OFFERED t0
    JOIN SIS_DEPARTMENT t1 ON t0.OFFER_DEPT_CODE = t1.DEPARTMENT_CODE
    JOIN SIS_SUBJECT_CODE t2 ON t1.DEPARTMENT_CODE = t2.DEPARTMENT_CODE
    WHERE t0.TERM_CODE = '2014FA'
      AND t0.NUM_ENROLLED_STUDENTS > 5
      AND t1.DEPARTMENT_NAME = 'Mathematics'
),
Subq2 AS (
    SELECT STDDEV(t0.NUM_ENROLLED_STUDENTS) / AVG(t0.NUM_ENROLLED_STUDENTS) AS coefficient_of_variation
    FROM TIP_SUBJECT_OFFERED t0
    WHERE t0.OFFER_DEPT_NAME = 'Mathematics'
)
SELECT s1.SUBJECT_CODE,
       s1.SUBJECT_CODE_DESC,
       s1.DEPARTMENT_NAME,
       s1.SCHOOL_NAME,
       s1.SUBJECT_TITLE,
       s1.NUM_ENROLLED_STUDENTS,
       s1.window_column,
       s2.coefficient_of_variation
FROM Subq1 s1
CROSS JOIN Subq2 s2
ORDER BY s1.DEPARTMENT_NAME, s1.SUBJECT_CODE