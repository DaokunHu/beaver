WITH inner_cte AS (
  SELECT de.DEPARTMENT_NAME, de.total_enrollments, lss.COURSE_NUMBER, lss.subject_count, lss.min_total_units
  FROM (
    SELECT s.DEPARTMENT_NAME, SUM(s.SUBJECT_ENROLLMENT_NUMBER) AS total_enrollments
    FROM ACADEMIC_TERM_PARAMETER p
    JOIN ACADEMIC_TERMS t ON p.TERM_CODE = t.TERM_CODE
    JOIN SUBJECT_SUMMARY s ON t.TERM_CODE = s.TERM_CODE
    WHERE p.IS_CURRENT_TERM = 'Y'
    GROUP BY s.DEPARTMENT_NAME
    HAVING SUM(s.SUBJECT_ENROLLMENT_NUMBER) > 10
  ) de
  JOIN (
    SELECT l.OFFER_DEPT_NAME, l.COURSE_NUMBER,
           COUNT(DISTINCT l.LIBRARY_SUBJECT_OFFERED_KEY) AS subject_count,
           MIN(s.TOTAL_UNITS) AS min_total_units
    FROM LIBRARY_SUBJECT_OFFERED l
    JOIN TIP_DETAIL t ON l.SUBJECT_ID = t.SUBJECT_ID
    JOIN SUBJECT_OFFERED_SUMMARY s ON t.SUBJECT_ID = s.SUBJECT_ID
    WHERE s.NUM_ENROLLED_STUDENTS > 2
    GROUP BY l.OFFER_DEPT_NAME, l.COURSE_NUMBER
  ) lss ON de.DEPARTMENT_NAME = lss.OFFER_DEPT_NAME
)
SELECT ic.DEPARTMENT_NAME,
       ic.total_enrollments,
       ic.COURSE_NUMBER,
       ic.subject_count,
       ic.min_total_units,
       AVG(sos.NUM_ENROLLED_STUDENTS) AS avg_enrolled_students
FROM inner_cte ic
JOIN LIBRARY_SUBJECT_OFFERED lso
  ON ic.DEPARTMENT_NAME = lso.OFFER_DEPT_NAME
 AND ic.COURSE_NUMBER = lso.COURSE_NUMBER
JOIN SUBJECT_OFFERED_SUMMARY sos
  ON lso.SUBJECT_ID = sos.SUBJECT_ID
WHERE sos.NUM_ENROLLED_STUDENTS > 2
GROUP BY ic.DEPARTMENT_NAME, ic.total_enrollments, ic.COURSE_NUMBER, ic.subject_count, ic.min_total_units;