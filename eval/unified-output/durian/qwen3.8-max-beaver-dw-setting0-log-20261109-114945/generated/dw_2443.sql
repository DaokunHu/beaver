SELECT
    t.ACADEMIC_YEAR,
    t.ACADEMIC_YEAR_DESC,
    AVG(CASE WHEN c.DEPARTMENT_NAME = 'Mathematics' THEN c.TOTAL_UNITS END) AS math_avg_total_units,
    AVG(CASE WHEN c.DEPARTMENT_NAME = 'Mathematics' THEN c.TOTAL_UNITS END) - AVG(c.TOTAL_UNITS) AS difference_from_overall_avg
FROM ACADEMIC_TERMS t
JOIN COURSE_CATALOG_SUBJECT_OFFERED c
    ON t.TERM_CODE = c.EFFECTIVE_TERM_CODE
WHERE t.IS_REGULAR_TERM = 'Y'
GROUP BY t.ACADEMIC_YEAR, t.ACADEMIC_YEAR_DESC
ORDER BY t.ACADEMIC_YEAR;