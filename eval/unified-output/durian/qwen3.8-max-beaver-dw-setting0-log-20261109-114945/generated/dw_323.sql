SELECT d.DEPARTMENT_NAME,
       COUNT(DISTINCT s.SUBJECT_ID) AS num_degree_granting_subjects
FROM SUBJECT_OFFERED_SUMMARY s
JOIN SIS_COURSE_DESCRIPTION c ON s.COURSE_NUMBER = c.COURSE
JOIN SIS_DEPARTMENT d ON s.OFFER_DEPT_CODE = d.DEPARTMENT_CODE
WHERE s.TERM_CODE = '2014FA'
  AND c.IS_DEGREE_GRANTING = 'Y'
  AND s.NUM_ENROLLED_STUDENTS > 5
GROUP BY d.DEPARTMENT_NAME