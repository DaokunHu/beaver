SELECT d.DEPARTMENT_NAME,
       AVG(s.TOTAL_UNITS) AS avg_total_units,
       MAX(s.TOTAL_UNITS) - MIN(s.TOTAL_UNITS) AS total_units_range,
       VARIANCE(s.TOTAL_UNITS) AS total_units_variance
FROM SIS_DEPARTMENT d
JOIN COURSE_CATALOG_SUBJECT_OFFERED s ON d.DEPARTMENT_CODE = s.DEPARTMENT_CODE
WHERE s.ACADEMIC_YEAR = 2022
  AND d.IS_DEGREE_GRANTING = 'Y'
  AND d.DEPARTMENT_CODE <> '18'
GROUP BY d.DEPARTMENT_NAME
HAVING MAX(s.TOTAL_UNITS) > 9