SELECT tso.OFFER_DEPT_NAME,
       AVG(tso.NUM_ENROLLED_STUDENTS) AS avg_enrolled_students,
       STDDEV(tso.NUM_ENROLLED_STUDENTS) AS stddev_enrolled_students
FROM TIP_SUBJECT_OFFERED tso
JOIN TIP_DETAIL td ON tso.TIP_SUBJECT_OFFERED_KEY = td.TIP_SUBJECT_OFFERED_KEY
WHERE td.TIP_MATERIAL_STATUS_KEY <> 'NM'
GROUP BY tso.OFFER_DEPT_NAME WITH ROLLUP