SELECT MIN(c.CIP_PROGRAM_CODE) AS min_cip_program_code,
       COUNT(DISTINCT d.DEPARTMENT_CODE) AS total_departments,
       ad.SIS_ADMIN_DEPARTMENT_NAME
FROM SIS_COURSE_DESCRIPTION c
JOIN SIS_DEPARTMENT d ON c.DEPARTMENT = d.DEPARTMENT_CODE
JOIN SIS_ADMIN_DEPARTMENT ad ON d.DEPARTMENT_CODE = ad.SIS_ADMIN_DEPARTMENT_CODE
WHERE d.SCHOOL_NAME = 'Engineering'
  AND d.IS_DEGREE_GRANTING = 'Y'
  AND d.DEPARTMENT_NAME = 'Mechanical Engineering'
GROUP BY ad.SIS_ADMIN_DEPARTMENT_NAME