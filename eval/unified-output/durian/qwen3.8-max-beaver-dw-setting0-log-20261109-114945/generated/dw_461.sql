SELECT T1.DEPARTMENT_NAME,
       SUM(T2.CLEARING_COST_COLLECTOR)
FROM SIS_DEPARTMENT T1
INNER JOIN SIS_ADMIN_DEPARTMENT T2
        ON T1.DEPARTMENT_CODE = T2.SIS_ADMIN_DEPARTMENT_CODE
WHERE T1.IS_DEGREE_GRANTING = 'Y'
  AND T1.DEPT_BUDGET_CODE > 100000
  AND T1.DEPARTMENT_NAME != 'Mathematics'
  AND T1.DEPARTMENT_NAME != 'Physics'
GROUP BY T1.DEPARTMENT_NAME
HAVING SUM(T2.CLEARING_COST_COLLECTOR) > (
    SELECT AVG(T4.CLEARING_COST_COLLECTOR)
    FROM SIS_DEPARTMENT T3
    INNER JOIN SIS_ADMIN_DEPARTMENT T4
            ON T3.DEPARTMENT_CODE = T4.SIS_ADMIN_DEPARTMENT_CODE
    WHERE T3.IS_DEGREE_GRANTING = 'Y'
      AND T3.DEPT_BUDGET_CODE > 100000
      AND T3.DEPARTMENT_NAME != 'Mathematics'
      AND T3.DEPARTMENT_NAME != 'Physics'
)