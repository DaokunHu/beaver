SELECT T1.OFFER_DEPT_NAME,
       STDDEV(T1.NUM_ENROLLED_STUDENTS),
       AVG(T2.AREA),
       VARIANCE(T2.AREA),
       STDDEV(T2.AREA)
FROM SUBJECT_OFFERED T1
INNER JOIN FCLT_ROOMS T2 ON T1.MEET_PLACE = T2.FCLT_ROOM_KEY
WHERE T1.TERM_CODE = '2022FA'
  AND T1.OFFER_DEPT_CODE = '8'
  AND T2.AREA > 100
GROUP BY T1.OFFER_DEPT_NAME
HAVING COUNT(T1.SUBJECT_ID) > 10