SELECT d.DEPARTMENT_NAME,
       COUNT(*) AS num_subjects_offered,
       VARIANCE(s.TOTAL_UNITS) AS total_units_variance
FROM SIS_DEPARTMENT d
JOIN COURSE_CATALOG_SUBJECT_OFFERED s
  ON d.DEPARTMENT_CODE = s.DEPARTMENT_CODE
WHERE s.ACADEMIC_YEAR = 2022
  AND d.IS_DEGREE_GRANTING = 'Y'
  AND d.DEPARTMENT_NAME <> 'Political Science'
  AND d.DEPARTMENT_NAME <> 'Biology'
GROUP BY d.DEPARTMENT_NAME
ORDER BY num_subjects_offered DESC
LIMIT 10