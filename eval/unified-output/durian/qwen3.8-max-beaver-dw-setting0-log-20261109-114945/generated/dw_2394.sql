WITH cip_dept AS (
  SELECT d.DEPARTMENT_CODE, MAX(c.CIP_PROGRAM_CODE) AS max_cip_code
  FROM SIS_COURSE_DESCRIPTION c
  JOIN SIS_DEPARTMENT d ON c.DEPARTMENT = d.DEPARTMENT_CODE
  WHERE d.IS_DEGREE_GRANTING = 'Y' AND d.DEPARTMENT_NAME != 'Mathematics'
  GROUP BY d.DEPARTMENT_CODE
  HAVING MAX(c.CIP_PROGRAM_CODE) > 120000
),
base AS (
  SELECT t.TERM_CODE, d.DEPARTMENT_NAME, t.NUM_ENROLLED_STUDENTS,
         cd.max_cip_code, d.DEPARTMENT_FULL_NAME
  FROM TIP_SUBJECT_OFFERED t
  JOIN SIS_DEPARTMENT d ON t.OFFER_DEPT_CODE = d.DEPARTMENT_CODE
  JOIN cip_dept cd ON d.DEPARTMENT_CODE = cd.DEPARTMENT_CODE
  WHERE t.OFFER_DEPT_NAME = 'Chemistry' AND t.IS_NO_COURSE_MATERIAL = 'N'
)
SELECT CASE WHEN LAG(term) OVER (ORDER BY term_sort, dept_sort) = term THEN NULL ELSE term END AS term,
       dept AS department_name,
       avg_enrolled,
       stddev_enrolled,
       max_cip_code,
       dept_full_name
FROM (
  SELECT CASE WHEN GROUPING(TERM_CODE) = 1 AND GROUPING(DEPARTMENT_NAME) = 1 THEN 'zzz' ELSE TERM_CODE END AS term_sort,
         CASE WHEN GROUPING(TERM_CODE) = 0 AND GROUPING(DEPARTMENT_NAME) = 1 THEN 'SUBTOTAL'
              WHEN GROUPING(TERM_CODE) = 1 AND GROUPING(DEPARTMENT_NAME) = 1 THEN 'TOTAL'
              ELSE TERM_CODE END AS term,
         CASE WHEN GROUPING(TERM_CODE) = 0 AND GROUPING(DEPARTMENT_NAME) = 1 THEN 'zzz' ELSE DEPARTMENT_NAME END AS dept_sort,
         DEPARTMENT_NAME AS dept,
         AVG(NUM_ENROLLED_STUDENTS) AS avg_enrolled,
         STDDEV(NUM_ENROLLED_STUDENTS) AS stddev_enrolled,
         MAX(max_cip_code) AS max_cip_code,
         MAX(DEPARTMENT_FULL_NAME) AS dept_full_name
  FROM base
  GROUP BY TERM_CODE, DEPARTMENT_NAME WITH ROLLUP
) tbltmp
ORDER BY term_sort, dept_sort