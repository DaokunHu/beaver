WITH Subq1 AS (
    SELECT
        t0.SUBJECT_ID,
        t0.SUBJECT_TITLE,
        t0.OFFER_DEPT_CODE,
        t0.OFFER_DEPT_NAME,
        t0.NUM_ENROLLED_STUDENTS,
        t1.DEPARTMENT_FULL_NAME,
        t1.SCHOOL_NAME,
        MIN(t0.NUM_ENROLLED_STUDENTS) OVER (PARTITION BY t0.OFFER_DEPT_CODE ORDER BY t0.OFFER_DEPT_CODE) AS min_enrolled_per_dept_code
    FROM TIP_SUBJECT_OFFERED t0
    JOIN STUDENT_DEPARTMENT t1 ON t0.OFFER_DEPT_CODE = t1.DEPARTMENT_CODE
    WHERE t0.TERM_CODE = '2017JA'
      AND t0.OFFER_DEPT_NAME = 'Chemistry'
),
Subq2 AS (
    SELECT
        d.DEPARTMENT_CODE,
        d.DEPARTMENT_NAME,
        VARIANCE(s.TOTAL_UNITS) AS units_variance,
        AVG(s.NUM_ENROLLED_STUDENTS) AS avg_enrolled_students
    FROM SIS_DEPARTMENT d
    JOIN SUBJECT_OFFERED_SUMMARY s ON d.DEPARTMENT_CODE = s.OFFER_DEPT_CODE
    WHERE s.TERM_CODE LIKE '2022%'
      AND d.IS_DEGREE_GRANTING = 'Y'
      AND d.DEPARTMENT_CODE <> '7'
    GROUP BY d.DEPARTMENT_CODE, d.DEPARTMENT_NAME
)
SELECT
    s1.SUBJECT_ID,
    s1.SUBJECT_TITLE,
    s1.OFFER_DEPT_CODE,
    s1.OFFER_DEPT_NAME,
    s1.NUM_ENROLLED_STUDENTS,
    s1.DEPARTMENT_FULL_NAME,
    s1.SCHOOL_NAME,
    s1.min_enrolled_per_dept_code,
    s2.DEPARTMENT_NAME,
    s2.units_variance,
    s2.avg_enrolled_students
FROM Subq1 s1
JOIN Subq2 s2 ON s1.OFFER_DEPT_CODE = s2.DEPARTMENT_CODE
ORDER BY s1.OFFER_DEPT_CODE, s2.units_variance DESC