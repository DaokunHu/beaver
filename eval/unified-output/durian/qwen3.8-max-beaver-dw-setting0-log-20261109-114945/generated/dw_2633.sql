WITH DepartmentStats AS (
    SELECT s.DEPARTMENT_NAME,
           s.SCHOOL_NAME,
           t.TERM_START_DATE,
           MAX(s.SUBJECT_ENROLLMENT_NUMBER) AS MAX_SUBJECT_ENROLLMENT_NUMBER
    FROM ACADEMIC_TERM_PARAMETER p
    JOIN ACADEMIC_TERMS t ON p.TERM_CODE = t.TERM_CODE
    JOIN SUBJECT_SUMMARY s ON t.TERM_CODE = s.TERM_CODE
    WHERE p.IS_CURRENT_TERM = 'Y'
    GROUP BY s.DEPARTMENT_NAME, s.SCHOOL_NAME, t.TERM_START_DATE
    HAVING MAX(s.SUBJECT_ENROLLMENT_NUMBER) > 5
),
SchoolRollup AS (
    SELECT NULL AS DEPARTMENT_NAME,
           SCHOOL_NAME,
           NULL AS TERM_START_DATE,
           SUM(MAX_SUBJECT_ENROLLMENT_NUMBER) AS MAX_SUBJECT_ENROLLMENT_NUMBER
    FROM DepartmentStats
    GROUP BY SCHOOL_NAME
)
SELECT DEPARTMENT_NAME, SCHOOL_NAME, TERM_START_DATE, MAX_SUBJECT_ENROLLMENT_NUMBER
FROM (
    SELECT DEPARTMENT_NAME, SCHOOL_NAME, TERM_START_DATE, MAX_SUBJECT_ENROLLMENT_NUMBER
    FROM DepartmentStats
    UNION ALL
    SELECT DEPARTMENT_NAME, SCHOOL_NAME, TERM_START_DATE, MAX_SUBJECT_ENROLLMENT_NUMBER
    FROM SchoolRollup
) combined
ORDER BY SCHOOL_NAME, DEPARTMENT_NAME