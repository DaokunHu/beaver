SELECT
  b.BUILDING_NAME,
  b.FISCAL_PERIOD,
  SUM(r.AREA) AS total_resident_labs_room_area,
  SUM(b.ASSIGNABLE_AREA) OVER (PARTITION BY b.CAMPUS_SECTOR ORDER BY b.FISCAL_PERIOD, b.BUILDING_NAME) AS running_sum_assignable_area,
  b.EXT_GROSS_AREA
FROM FCLT_BUILDING_HIST b
JOIN FCLT_ROOMS r ON b.FCLT_BUILDING_KEY = r.FCLT_BUILDING_KEY
JOIN FCLT_MAJOR_USE mu ON r.FCLT_MAJOR_USE_KEY = mu.FCLT_MAJOR_USE_KEY
WHERE b.BUILDING_TYPE = 'ACADEMIC'
  AND b.SITE = 'MIT'
  AND b.OWNERSHIP_TYPE = 'OWNED'
  AND b.FCLT_BUILDING_KEY <> '32'
  AND mu.MAJOR_USE IN ('RESIDENT', 'LABS')
GROUP BY b.BUILDING_NAME, b.FISCAL_PERIOD, b.CAMPUS_SECTOR, b.ASSIGNABLE_AREA, b.EXT_GROSS_AREA
HAVING SUM(r.AREA) > 1000
ORDER BY b.FISCAL_PERIOD, b.BUILDING_NAME