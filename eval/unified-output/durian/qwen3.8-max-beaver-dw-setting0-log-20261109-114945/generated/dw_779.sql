SELECT t.ACADEMIC_YEAR,
       t.ACADEMIC_YEAR_DESC,
       AVG(ccso.TOTAL_UNITS) AS avg_total_units,
       STDDEV(ccso.TOTAL_UNITS) AS stddev_total_units,
       VARIANCE(CASE WHEN t.TERM_STATUS = 'Previous' THEN ccso.TOTAL_UNITS END) AS variance_total_units
FROM ACADEMIC_TERMS t
JOIN COURSE_CATALOG_SUBJECT_OFFERED ccso
  ON t.TERM_CODE = ccso.EFFECTIVE_TERM_CODE
WHERE t.IS_REGULAR_TERM = 'Y'
  AND ccso.DEPARTMENT_NAME = 'Mathematics'
GROUP BY t.ACADEMIC_YEAR, t.ACADEMIC_YEAR_DESC
ORDER BY t.ACADEMIC_YEAR