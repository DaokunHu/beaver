WITH dept_cv AS (
    SELECT c.DEPARTMENT_NAME,
           STDDEV(c.TOTAL_UNITS) / NULLIF(AVG(c.TOTAL_UNITS), 0) AS coefficient_of_variation
    FROM COURSE_CATALOG_SUBJECT_OFFERED c
    JOIN ACADEMIC_TERMS t ON c.TERM_CODE = t.TERM_CODE
    WHERE t.IS_REGULAR_TERM = 'Y'
      AND c.DEPARTMENT_NAME <> 'Mathematics'
    GROUP BY c.DEPARTMENT_NAME
)
SELECT sp.MIT_ID,
       sp.FULL_NAME,
       msd.DEPARTMENT_NAME,
       msd.STUDENT_YEAR,
       SUM(sp.MIT_ID) OVER (PARTITION BY msd.STUDENT_YEAR ORDER BY sp.MIT_ID) AS running_sum_mit_id,
       cv.coefficient_of_variation
FROM SE_PERSON sp
JOIN MIT_STUDENT_DIRECTORY msd ON sp.FULL_NAME = msd.FULL_NAME
LEFT JOIN dept_cv cv ON msd.DEPARTMENT_NAME = cv.DEPARTMENT_NAME
WHERE sp.EMPLOYEE_TYPE = 'Student'
  AND msd.DEPARTMENT = '6'
  AND msd.DEPARTMENT_NAME = 'Electrical Eng & Computer Sci'