WITH Subq1 AS (
    SELECT t0.SUBJECT_TITLE,
           t1.DEPARTMENT_NAME,
           DENSE_RANK() OVER (ORDER BY t2.SUBJECT_CODE ROWS BETWEEN 2 PRECEDING AND CURRENT ROW) AS window_column
    FROM SUBJECT_OFFERED_SUMMARY t0
    JOIN SIS_COURSE_DESCRIPTION t1 ON t0.COURSE_NUMBER = t1.COURSE
    JOIN COURSE_CATALOG_SUBJECT_OFFERED t2 ON t1.COURSE = t2.SUBJECT_CODE
    WHERE t2.TERM_CODE = '2022FA'
      AND t0.TOTAL_UNITS = 12
),
Subq2 AS (
    SELECT t1.DEPARTMENT_NAME,
           t1.SCHOOL_NAME,
           COUNT(t0.SUBJECT_KEY) AS subject_count,
           MIN(t0.NUM_ENROLLED_STUDENTS) AS min_enrolled
    FROM SUBJECT_OFFERED t0
    JOIN SIS_SUBJECT_CODE t1 ON t0.COURSE_NUMBER = t1.COURSE_NUMBER
    WHERE t0.NUM_ENROLLED_STUDENTS > 3
    GROUP BY t1.DEPARTMENT_NAME, t1.SCHOOL_NAME
)
SELECT s1.SUBJECT_TITLE,
       s1.DEPARTMENT_NAME,
       s1.window_column,
       s2.subject_count,
       s2.min_enrolled
FROM Subq1 s1
JOIN Subq2 s2 ON s1.DEPARTMENT_NAME = s2.DEPARTMENT_NAME