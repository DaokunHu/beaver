WITH dept_avg AS (
    SELECT AVG(s.NUM_ENROLLED_STUDENTS) AS avg_enrolled
    FROM SUBJECT_OFFERED_SUMMARY s
    JOIN SIS_DEPARTMENT d ON s.OFFER_DEPT_CODE = d.DEPARTMENT_CODE
    WHERE d.DEPARTMENT_NAME = 'Mathematics' AND d.DEPARTMENT_CODE = '18'
)
SELECT d.DEPARTMENT_NAME,
       s.SUBJECT_TITLE,
       s.NUM_ENROLLED_STUDENTS,
       d.SCHOOL_NAME,
       DENSE_RANK() OVER (PARTITION BY d.DEPARTMENT_CODE ORDER BY d.DEPARTMENT_CODE) AS window_column
FROM SUBJECT_OFFERED_SUMMARY s
JOIN SIS_DEPARTMENT d ON s.OFFER_DEPT_CODE = d.DEPARTMENT_CODE
CROSS JOIN dept_avg a
WHERE d.DEPARTMENT_NAME = 'Mathematics'
  AND d.DEPARTMENT_CODE = '18'
  AND s.NUM_ENROLLED_STUDENTS > 0
  AND d.IS_DEGREE_GRANTING = 'Y'
  AND s.NUM_ENROLLED_STUDENTS > a.avg_enrolled