SELECT
  T1.MASTER_DEPT_HIER_LEVEL_2_NAME,
  T2.ORGANIZATION_NAME,
  COUNT(T2.FCLT_ORGANIZATION_KEY) AS number_of_organizations,
  MIN(T2.ORGANIZATION_NUMBER) AS min_organization_number,
  EXP(AVG(LN(T3.NUM_OF_SUPERVISEES))) AS geometric_mean_num_of_supervisees,
  SUM(T3.RESEARCH_VOLUME) AS total_research_volume
FROM MASTER_DEPT_HIERARCHY T1
JOIN FCLT_ORGANIZATION T2 ON T1.DLC_KEY = T2.DLC_KEY
JOIN SPACE_SUPERVISOR_USAGE T3 ON T3.DEPT_NAMES = T2.DLC_KEY
WHERE T2.ASSIGNABLE = 1
  AND T3.NUM_OF_SUPERVISEES > 0
GROUP BY T1.MASTER_DEPT_HIER_LEVEL_2_NAME, T2.ORGANIZATION_NAME
ORDER BY number_of_organizations DESC,
         geometric_mean_num_of_supervisees DESC,
         total_research_volume DESC