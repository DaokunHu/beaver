SELECT scd.DEPARTMENT_NAME,
       scd.SCHOOL_NAME,
       COUNT(DISTINCT scd.COURSE) AS num_unique_courses,
       MIN(scd.CIP_PROGRAM_CODE) AS min_cip_program_code
FROM SIS_COURSE_DESCRIPTION scd
JOIN SIS_DEPARTMENT sd ON scd.DEPARTMENT = sd.DEPARTMENT_CODE
WHERE sd.IS_DEGREE_GRANTING = 'Y'
  AND sd.DEPARTMENT_NAME = 'Mathematics'
  AND sd.DEPARTMENT_CODE = '18'
GROUP BY scd.DEPARTMENT_NAME, scd.SCHOOL_NAME