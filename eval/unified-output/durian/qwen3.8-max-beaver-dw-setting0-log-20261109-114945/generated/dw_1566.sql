WITH room_area AS (
  SELECT h.FCLT_BUILDING_HIST_KEY,
         h.BUILDING_NAME,
         h.FISCAL_PERIOD,
         h.CAMPUS_SECTOR,
         h.ASSIGNABLE_AREA,
         h.EXT_GROSS_AREA,
         SUM(r.AREA) AS total_room_area
  FROM FCLT_BUILDING_HIST h
  JOIN FCLT_ROOMS r ON h.FCLT_BUILDING_KEY = r.FCLT_BUILDING_KEY
  JOIN FCLT_MAJOR_USE mu ON r.FCLT_MAJOR_USE_KEY = mu.FCLT_MAJOR_USE_KEY
  WHERE h.BUILDING_TYPE = 'ACADEMIC'
    AND h.SITE = 'MIT'
    AND h.OWNERSHIP_TYPE = 'OWNED'
    AND mu.MAJOR_USE IN ('RESIDENT', 'LABS')
    AND h.FCLT_BUILDING_KEY <> '32'
  GROUP BY h.FCLT_BUILDING_HIST_KEY, h.BUILDING_NAME, h.FISCAL_PERIOD, h.CAMPUS_SECTOR, h.ASSIGNABLE_AREA, h.EXT_GROSS_AREA
  HAVING SUM(r.AREA) > 1000
)
SELECT BUILDING_NAME,
       FISCAL_PERIOD,
       total_room_area,
       SUM(ASSIGNABLE_AREA) OVER (PARTITION BY CAMPUS_SECTOR ORDER BY FISCAL_PERIOD, BUILDING_NAME) AS running_sum_assignable_area,
       EXT_GROSS_AREA
FROM room_area
ORDER BY FISCAL_PERIOD, BUILDING_NAME