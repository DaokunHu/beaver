SELECT
  r.MAJOR_USE_DESC,
  r.ORGANIZATION_NAME,
  COUNT(*) AS num_rooms,
  MIN(r.FLOOR) AS min_floor_number,
  EXP(AVG(LN(s.NUM_OF_SUPERVISEES))) AS geometric_mean_supervisees,
  SUM(s.RESEARCH_VOLUME) AS total_research_volume
FROM FCLT_ROOMS r
JOIN FCLT_ORGANIZATION o ON r.FCLT_ORGANIZATION_KEY = o.FCLT_ORGANIZATION_KEY
JOIN SPACE_SUPERVISOR_USAGE s ON o.DLC_KEY = s.DEPT_NAMES
WHERE r.AREA > 100
  AND r.ACCESS_LEVEL = 1
  AND s.NUM_OF_SUPERVISEES > 0
  AND s.RESEARCH_VOLUME > 0
GROUP BY r.MAJOR_USE_DESC, r.ORGANIZATION_NAME