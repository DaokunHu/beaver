SELECT sd.DEPARTMENT_CODE,
       sd.DEPARTMENT_NAME,
       SUM(sos.NUM_ENROLLED_STUDENTS) AS total_enrolled_students,
       NULL AS unique_course_titles,
       'High Enrollment Mathematics' AS reason_for_inclusion
FROM SIS_DEPARTMENT sd
JOIN SUBJECT_OFFERED_SUMMARY sos ON sd.DEPARTMENT_CODE = sos.OFFER_DEPT_CODE
JOIN SIS_SUBJECT_CODE ssc ON ssc.DEPARTMENT_CODE = sd.DEPARTMENT_CODE
WHERE sd.DEPARTMENT_NAME = 'Mathematics'
GROUP BY sd.DEPARTMENT_CODE, sd.DEPARTMENT_NAME
HAVING SUM(sos.NUM_ENROLLED_STUDENTS) > (
    SELECT AVG(t.total_enrolled) + STDDEV(t.total_enrolled)
    FROM (
        SELECT SUM(sos2.NUM_ENROLLED_STUDENTS) AS total_enrolled
        FROM SIS_DEPARTMENT sd2
        JOIN SUBJECT_OFFERED_SUMMARY sos2 ON sd2.DEPARTMENT_CODE = sos2.OFFER_DEPT_CODE
        JOIN SIS_SUBJECT_CODE ssc2 ON ssc2.DEPARTMENT_CODE = sd2.DEPARTMENT_CODE
        GROUP BY sd2.DEPARTMENT_CODE
    ) t
)
UNION ALL
SELECT ic.DEPARTMENT_CODE,
       ic.DEPARTMENT_NAME,
       NULL AS total_enrolled_students,
       COUNT(DISTINCT ccc.SUBJECT_TITLE) AS unique_course_titles,
       'Degree-Granting with Many Courses' AS reason_for_inclusion
FROM (
    SELECT sd.DEPARTMENT_CODE, sd.DEPARTMENT_NAME, COUNT(*) AS num_courses
    FROM SIS_DEPARTMENT sd
    JOIN CIS_COURSE_CATALOG ccc ON sd.DEPARTMENT_CODE = ccc.DEPARTMENT_CODE
    WHERE sd.IS_DEGREE_GRANTING = 'Y'
      AND sd.DEPARTMENT_CODE <> '6'
    GROUP BY sd.DEPARTMENT_CODE, sd.DEPARTMENT_NAME
) ic
JOIN CIS_COURSE_CATALOG ccc ON ic.DEPARTMENT_CODE = ccc.DEPARTMENT_CODE
WHERE ic.num_courses >= 5
GROUP BY ic.DEPARTMENT_CODE, ic.DEPARTMENT_NAME