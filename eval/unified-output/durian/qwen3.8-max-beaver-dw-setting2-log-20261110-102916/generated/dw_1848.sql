WITH inner_cte AS (
    SELECT fb.FCLT_BUILDING_KEY,
           fb.BUILDING_NAME,
           SUM(fr.AREA) AS total_room_area
    FROM FCLT_ROOMS fr
    JOIN FCLT_BUILDING fb ON fr.FCLT_BUILDING_KEY = fb.FCLT_BUILDING_KEY
    WHERE fr.MAJOR_USE_DESC IN ('RESIDENT', 'LABS')
      AND fb.BUILDING_TYPE = 'ACADEMIC'
      AND fb.SITE = 'MIT'
      AND fb.OWNERSHIP_TYPE = 'OWNED'
      AND fb.FCLT_BUILDING_KEY <> '32'
    GROUP BY fb.FCLT_BUILDING_KEY, fb.BUILDING_NAME
    HAVING SUM(fr.AREA) > 1000
)
SELECT ic.BUILDING_NAME,
       fbh.FISCAL_PERIOD,
       ic.total_room_area,
       SUM(fbh.ASSIGNABLE_AREA) OVER (
           PARTITION BY fb.CAMPUS_SECTOR
           ORDER BY fb.FCLT_BUILDING_KEY, fbh.FISCAL_PERIOD
           ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
       ) AS running_assignable_area,
       fb.EXT_GROSS_AREA
FROM inner_cte ic
JOIN FCLT_BUILDING fb ON ic.FCLT_BUILDING_KEY = fb.FCLT_BUILDING_KEY
JOIN FCLT_BUILDING_HIST fbh ON fb.FCLT_BUILDING_KEY = fbh.FCLT_BUILDING_KEY
ORDER BY fbh.FISCAL_PERIOD, ic.BUILDING_NAME