WITH TopSubjects AS (
  SELECT ss.SUBJECT_TITLE,
         ss.DEPARTMENT_NAME,
         COUNT(td.TIP_MATERIAL_KEY) AS material_count,
         ss.SUBJECT_ID
  FROM TIP_DETAIL td
  JOIN ACADEMIC_TERMS at ON td.TERM_CODE = at.TERM_CODE
  JOIN SUBJECT_SUMMARY ss ON at.TERM_CODE = ss.TERM_CODE AND td.SUBJECT_ID = ss.SUBJECT_ID
  WHERE at.IS_REGULAR_TERM = 'Y'
  GROUP BY ss.SUBJECT_TITLE, ss.DEPARTMENT_NAME, ss.SUBJECT_ID
  ORDER BY material_count DESC
  LIMIT 10
),
Subjects2014FA AS (
  SELECT lso.SUBJECT_TITLE,
         lso.OFFER_DEPT_NAME,
         lso.RESPONSIBLE_FACULTY_NAME,
         td.TIP_MATERIAL_STATUS_KEY,
         sos.TOTAL_UNITS,
         MIN(sos.TOTAL_UNITS) OVER (ORDER BY sos.COURSE_NUMBER ROWS BETWEEN 3 PRECEDING AND 1 FOLLOWING) AS window_column,
         lso.SUBJECT_ID
  FROM LIBRARY_SUBJECT_OFFERED lso
  JOIN TIP_DETAIL td ON lso.SUBJECT_ID = td.SUBJECT_ID
  JOIN SUBJECT_OFFERED_SUMMARY sos ON td.SUBJECT_ID = sos.SUBJECT_ID
  WHERE lso.TERM_CODE = '2014FA' AND lso.NUM_ENROLLED_STUDENTS > 0
),
CombinedSubjects AS (
  SELECT ts.SUBJECT_TITLE,
         ts.DEPARTMENT_NAME,
         ts.material_count,
         NULL AS OFFER_DEPT_NAME,
         NULL AS RESPONSIBLE_FACULTY_NAME,
         NULL AS TIP_MATERIAL_STATUS_KEY,
         NULL AS TOTAL_UNITS,
         NULL AS window_column,
         'TopSubjects' AS Reason
  FROM TopSubjects ts
  UNION ALL
  SELECT s2014.SUBJECT_TITLE,
         NULL AS DEPARTMENT_NAME,
         NULL AS material_count,
         s2014.OFFER_DEPT_NAME,
         s2014.RESPONSIBLE_FACULTY_NAME,
         s2014.TIP_MATERIAL_STATUS_KEY,
         s2014.TOTAL_UNITS,
         s2014.window_column,
         'Subjects2014FA' AS Reason
  FROM Subjects2014FA s2014
)
SELECT c.SUBJECT_TITLE,
       c.DEPARTMENT_NAME,
       c.material_count,
       c.OFFER_DEPT_NAME,
       c.RESPONSIBLE_FACULTY_NAME,
       c.TIP_MATERIAL_STATUS_KEY,
       c.TOTAL_UNITS,
       c.window_column,
       sd.SCHOOL_NAME,
       ad.DEPARTMENT_PHONE_NUMBER,
       c.Reason
FROM CombinedSubjects c
LEFT JOIN SIS_DEPARTMENT sd ON COALESCE(c.DEPARTMENT_NAME, c.OFFER_DEPT_NAME) = sd.DEPARTMENT_NAME
LEFT JOIN SIS_ADMIN_DEPARTMENT ad ON sd.DEPARTMENT_CODE = ad.SIS_ADMIN_DEPARTMENT_CODE
ORDER BY c.SUBJECT_TITLE