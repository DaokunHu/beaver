WITH filtered_buildings AS (
    SELECT fb.FCLT_BUILDING_KEY,
           fb.BUILDING_NAME,
           fb.CAMPUS_SECTOR,
           fb.EXT_GROSS_AREA,
           SUM(fr.AREA) AS total_room_area
    FROM FCLT_ROOMS fr
    JOIN FCLT_BUILDING fb ON fr.FCLT_BUILDING_KEY = fb.FCLT_BUILDING_KEY
    WHERE fr.MAJOR_USE_DESC IN ('RESIDENT', 'LABS')
      AND fb.BUILDING_TYPE = 'ACADEMIC'
      AND fb.SITE = 'MIT'
      AND fb.OWNERSHIP_TYPE = 'OWNED'
      AND fb.FCLT_BUILDING_KEY <> '32'
    GROUP BY fb.FCLT_BUILDING_KEY, fb.BUILDING_NAME, fb.CAMPUS_SECTOR, fb.EXT_GROSS_AREA
    HAVING SUM(fr.AREA) > 1000
)
SELECT fb2.BUILDING_NAME,
       fbh.FISCAL_PERIOD,
       fb2.total_room_area,
       SUM(fbh.ASSIGNABLE_AREA) OVER (
           PARTITION BY fb2.CAMPUS_SECTOR
           ORDER BY fb2.FCLT_BUILDING_KEY, fbh.FISCAL_PERIOD
           ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
       ) AS running_assignable_area,
       fb2.EXT_GROSS_AREA
FROM filtered_buildings fb2
JOIN FCLT_BUILDING_HIST fbh ON fb2.FCLT_BUILDING_KEY = fbh.FCLT_BUILDING_KEY
ORDER BY fbh.FISCAL_PERIOD, fb2.BUILDING_NAME