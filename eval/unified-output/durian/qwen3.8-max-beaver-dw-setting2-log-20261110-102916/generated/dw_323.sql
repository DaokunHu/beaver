SELECT scd.DEPARTMENT_NAME, COUNT(*) AS num_degree_granting_subjects
FROM SIS_COURSE_DESCRIPTION scd
JOIN SIS_SUBJECT_CODE ssc ON scd.COURSE = ssc.COURSE_NUMBER
JOIN LIBRARY_SUBJECT_OFFERED lso ON ssc.COURSE_NUMBER = lso.COURSE_NUMBER
WHERE lso.TERM_CODE = '2014FA'
  AND lso.NUM_ENROLLED_STUDENTS > 5
  AND scd.IS_DEGREE_GRANTING = 'Y'
GROUP BY scd.DEPARTMENT_NAME
ORDER BY scd.DEPARTMENT_NAME