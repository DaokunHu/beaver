WITH MathAvg AS (
    SELECT ACADEMIC_TERMS.ACADEMIC_YEAR,
           ACADEMIC_TERMS.ACADEMIC_YEAR_DESC,
           AVG(COURSE_CATALOG_SUBJECT_OFFERED.TOTAL_UNITS) AS avg_math_total_units
    FROM ACADEMIC_TERMS_ALL
    JOIN ACADEMIC_TERMS ON ACADEMIC_TERMS_ALL.TERM_CODE = ACADEMIC_TERMS.TERM_CODE
    JOIN COURSE_CATALOG_SUBJECT_OFFERED ON ACADEMIC_TERMS.TERM_CODE = COURSE_CATALOG_SUBJECT_OFFERED.TERM_CODE
    WHERE ACADEMIC_TERMS.IS_REGULAR_TERM = 'Y'
      AND COURSE_CATALOG_SUBJECT_OFFERED.DEPARTMENT_NAME = 'Mathematics'
    GROUP BY ACADEMIC_TERMS.ACADEMIC_YEAR, ACADEMIC_TERMS.ACADEMIC_YEAR_DESC
),
AllAvg AS (
    SELECT ACADEMIC_TERMS.ACADEMIC_YEAR,
           AVG(COURSE_CATALOG_SUBJECT_OFFERED.TOTAL_UNITS) AS avg_all_total_units
    FROM ACADEMIC_TERMS_ALL
    JOIN ACADEMIC_TERMS ON ACADEMIC_TERMS_ALL.TERM_CODE = ACADEMIC_TERMS.TERM_CODE
    JOIN COURSE_CATALOG_SUBJECT_OFFERED ON ACADEMIC_TERMS.TERM_CODE = COURSE_CATALOG_SUBJECT_OFFERED.TERM_CODE
    WHERE ACADEMIC_TERMS.IS_REGULAR_TERM = 'Y'
    GROUP BY ACADEMIC_TERMS.ACADEMIC_YEAR
)
SELECT m.ACADEMIC_YEAR,
       m.ACADEMIC_YEAR_DESC,
       m.avg_math_total_units,
       m.avg_math_total_units - a.avg_all_total_units AS difference_from_all_subjects_avg
FROM MathAvg m
JOIN AllAvg a ON m.ACADEMIC_YEAR = a.ACADEMIC_YEAR
ORDER BY m.ACADEMIC_YEAR;