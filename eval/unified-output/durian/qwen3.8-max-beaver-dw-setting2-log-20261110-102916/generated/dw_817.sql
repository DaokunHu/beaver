WITH largest_room_per_floor AS (
  SELECT sf.FLOOR_NAME,
         sd.BUILDING_ROOM_NAME,
         sd.ROOM_SQUARE_FOOTAGE,
         sd.FLOOR_KEY
  FROM SPACE_DETAIL sd
  JOIN SPACE_FLOOR sf ON sd.FLOOR_KEY = sf.FLOOR_KEY
  WHERE sd.BUILDING_KEY = 32
    AND sd.WAREHOUSE_LOAD_DATE = '19-DEC-24'
    AND sd.ROOM_SQUARE_FOOTAGE > 100
    AND sd.ROOM_SQUARE_FOOTAGE = (
          SELECT MAX(sd2.ROOM_SQUARE_FOOTAGE)
          FROM SPACE_DETAIL sd2
          WHERE sd2.BUILDING_KEY = 32
            AND sd2.FLOOR_KEY = sd.FLOOR_KEY
            AND sd2.WAREHOUSE_LOAD_DATE = '19-DEC-24'
        )
),
room_and_avg_per_floor AS (
  SELECT sd.BUILDING_ROOM_NAME,
         sd.ROOM_NUMBER,
         sd.ROOM_SQUARE_FOOTAGE,
         sf.FLOOR_NAME,
         AVG(sd2.ROOM_SQUARE_FOOTAGE) AS AVG_ROOM_SQUARE_FOOTAGE_PER_FLOOR,
         sd.FLOOR_KEY
  FROM SPACE_DETAIL sd
  JOIN SPACE_FLOOR sf ON sd.FLOOR_KEY = sf.FLOOR_KEY
  JOIN SPACE_DETAIL sd2 ON sd2.FLOOR_KEY = sd.FLOOR_KEY
  WHERE sd.BUILDING_KEY = 32
    AND sd.ROOM_SQUARE_FOOTAGE > 10
  GROUP BY sd.BUILDING_ROOM_NAME, sd.ROOM_NUMBER, sd.ROOM_SQUARE_FOOTAGE, sf.FLOOR_NAME, sd.FLOOR_KEY
)
SELECT lrf.FLOOR_NAME,
       lrf.BUILDING_ROOM_NAME AS LARGEST_ROOM_NAME,
       lrf.ROOM_SQUARE_FOOTAGE AS LARGEST_ROOM_SQUARE_FOOTAGE,
       raf.BUILDING_ROOM_NAME,
       raf.ROOM_NUMBER,
       raf.ROOM_SQUARE_FOOTAGE,
       raf.AVG_ROOM_SQUARE_FOOTAGE_PER_FLOOR
FROM largest_room_per_floor lrf
JOIN room_and_avg_per_floor raf ON lrf.FLOOR_NAME = raf.FLOOR_NAME
ORDER BY lrf.FLOOR_NAME, raf.ROOM_SQUARE_FOOTAGE