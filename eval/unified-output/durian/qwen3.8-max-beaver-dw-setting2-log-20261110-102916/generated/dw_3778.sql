WITH EngCourses AS (
  SELECT t0.COURSE_DESCRIPTION,
         t1.DEPARTMENT_NAME,
         dense_rank() OVER (ORDER BY t1.DEPT_BUDGET_CODE ROWS BETWEEN 2 PRECEDING AND CURRENT ROW) AS window_column,
         t1.DEPARTMENT_CODE
  FROM SIS_COURSE_DESCRIPTION t0
  JOIN SIS_DEPARTMENT t1 ON t0.DEPARTMENT = t1.DEPARTMENT_CODE
  WHERE t1.SCHOOL_NAME = 'Engineering' AND t1.IS_DEGREE_GRANTING = 'Y'
), TermParams AS (
  SELECT t0.TERM_PARAMETER,
         t0.TERM_CODE,
         t1.ACADEMIC_YEAR,
         t2.DEPARTMENT_NAME,
         SUM(t1.ACADEMIC_YEAR) OVER (PARTITION BY t2.DEPARTMENT_NAME ORDER BY t1.ACADEMIC_YEAR) AS window_column,
         t2.DEPARTMENT_CODE
  FROM ACADEMIC_TERM_PARAMETER t0
  JOIN ACADEMIC_TERMS t1 ON t0.TERM_CODE = t1.TERM_CODE
  JOIN COURSE_CATALOG_SUBJECT_OFFERED t2 ON t1.TERM_CODE = t2.EFFECTIVE_TERM_CODE
  WHERE t0.TERM_INDICATOR = 'C'
)
SELECT ec.COURSE_DESCRIPTION,
       ec.DEPARTMENT_NAME,
       ec.window_column,
       tp.TERM_PARAMETER,
       tp.TERM_CODE,
       tp.ACADEMIC_YEAR,
       tp.DEPARTMENT_NAME,
       tp.window_column
FROM EngCourses ec
JOIN TermParams tp ON ec.DEPARTMENT_CODE = tp.DEPARTMENT_CODE