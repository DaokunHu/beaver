WITH Subquery1 AS (
  SELECT t1.SUBJECT_CODE,
         t1.SUBJECT_CODE_DESC,
         t0.DEPARTMENT_NAME,
         t1.SCHOOL_NAME,
         AVG(t0.DEPT_BUDGET_CODE) OVER (PARTITION BY t1.SCHOOL_NAME ORDER BY t0.DEPARTMENT_NAME) AS avg_dept_budget_code
  FROM SIS_DEPARTMENT t0
  JOIN SIS_SUBJECT_CODE t1 ON t0.SCHOOL_CODE = t1.SCHOOL_CODE
  WHERE t0.IS_DEGREE_GRANTING = 'Y'
    AND t0.DEPARTMENT_NAME = 'Mathematics'
),
Subquery2 AS (
  SELECT s.SUBJECT_TITLE,
         s.TOTAL_UNITS,
         d.DEPARTMENT_NAME,
         d.SCHOOL_NAME,
         DENSE_RANK() OVER (PARTITION BY d.DEPARTMENT_CODE ORDER BY d.DEPARTMENT_CODE) AS window_column,
         COUNT(s.SUBJECT_OFFERED_SUMMARY_KEY) OVER (PARTITION BY d.DEPARTMENT_CODE) AS num_subjects_offered,
         d.DEPARTMENT_CODE
  FROM SUBJECT_OFFERED_SUMMARY s
  JOIN SIS_DEPARTMENT d ON d.DEPARTMENT_CODE = s.OFFER_DEPT_CODE
  JOIN SIS_SUBJECT_CODE sc ON sc.DEPARTMENT_CODE = d.DEPARTMENT_CODE
  WHERE d.IS_DEGREE_GRANTING = 'Y'
    AND sc.SUBJECT_CODE_DESC IS NOT NULL
    AND d.DEPARTMENT_NAME = 'Mathematics'
)
SELECT sq1.SUBJECT_CODE,
       sq1.SUBJECT_CODE_DESC,
       sq1.DEPARTMENT_NAME,
       sq1.SCHOOL_NAME,
       sq1.avg_dept_budget_code,
       sq2.SUBJECT_TITLE,
       sq2.TOTAL_UNITS,
       sq2.window_column,
       sq2.num_subjects_offered
FROM Subquery1 sq1
JOIN SIS_DEPARTMENT d ON sq1.DEPARTMENT_NAME = d.DEPARTMENT_NAME AND sq1.SCHOOL_NAME = d.SCHOOL_NAME
JOIN Subquery2 sq2 ON d.DEPARTMENT_CODE = sq2.DEPARTMENT_CODE
ORDER BY sq1.DEPARTMENT_NAME, sq2.window_column