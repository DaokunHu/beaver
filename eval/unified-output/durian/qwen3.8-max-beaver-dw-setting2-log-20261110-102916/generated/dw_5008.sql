WITH record_count_variance_cte AS (
    SELECT ACADEMIC_TERMS_ALL.ACADEMIC_YEAR,
           ACADEMIC_TERMS_ALL.ACADEMIC_YEAR_DESC,
           VARIANCE(TIP_DETAIL.RECORD_COUNT) AS record_count_variance
    FROM TIP_DETAIL
    JOIN ACADEMIC_TERMS_ALL ON TIP_DETAIL.TERM_CODE = ACADEMIC_TERMS_ALL.TERM_CODE
    JOIN ACADEMIC_TERM_PARAMETER ON ACADEMIC_TERMS_ALL.TERM_CODE = ACADEMIC_TERM_PARAMETER.TERM_CODE
    WHERE ACADEMIC_TERM_PARAMETER.TERM_PARAMETER IN ('SIS_CURRENT_TERM', 'SIS_PREVIOUS_TERM')
    GROUP BY ACADEMIC_TERMS_ALL.ACADEMIC_YEAR, ACADEMIC_TERMS_ALL.ACADEMIC_YEAR_DESC
),
geometric_mean_record_count_cte AS (
    SELECT ACADEMIC_TERMS_ALL.ACADEMIC_YEAR,
           ACADEMIC_TERMS_ALL.ACADEMIC_YEAR_DESC,
           EXP(AVG(LN(TIP_DETAIL.RECORD_COUNT))) AS geometric_mean_record_count
    FROM COURSE_CATALOG_SUBJECT_OFFERED
    JOIN ACADEMIC_TERMS_ALL ON COURSE_CATALOG_SUBJECT_OFFERED.TERM_CODE = ACADEMIC_TERMS_ALL.TERM_CODE
    JOIN TIP_DETAIL ON ACADEMIC_TERMS_ALL.TERM_CODE = TIP_DETAIL.TERM_CODE
    WHERE TIP_DETAIL.RECORD_COUNT > 0
      AND TIP_DETAIL.TIP_MATERIAL_STATUS_KEY = 'RQ'
    GROUP BY ACADEMIC_TERMS_ALL.ACADEMIC_YEAR, ACADEMIC_TERMS_ALL.ACADEMIC_YEAR_DESC
),
unique_department_count_cte AS (
    SELECT ACADEMIC_TERMS_ALL.ACADEMIC_YEAR,
           ACADEMIC_TERMS_ALL.ACADEMIC_YEAR_DESC,
           COUNT(DISTINCT COURSE_CATALOG_SUBJECT_OFFERED.DEPARTMENT_CODE) AS unique_department_count
    FROM COURSE_CATALOG_SUBJECT_OFFERED
    JOIN ACADEMIC_TERMS_ALL ON COURSE_CATALOG_SUBJECT_OFFERED.TERM_CODE = ACADEMIC_TERMS_ALL.TERM_CODE
    GROUP BY ACADEMIC_TERMS_ALL.ACADEMIC_YEAR, ACADEMIC_TERMS_ALL.ACADEMIC_YEAR_DESC
)
SELECT rcv.ACADEMIC_YEAR,
       rcv.ACADEMIC_YEAR_DESC,
       rcv.record_count_variance,
       gmr.geometric_mean_record_count,
       udc.unique_department_count
FROM record_count_variance_cte rcv
JOIN geometric_mean_record_count_cte gmr
  ON rcv.ACADEMIC_YEAR = gmr.ACADEMIC_YEAR
 AND rcv.ACADEMIC_YEAR_DESC = gmr.ACADEMIC_YEAR_DESC
JOIN unique_department_count_cte udc
  ON rcv.ACADEMIC_YEAR = udc.ACADEMIC_YEAR
 AND rcv.ACADEMIC_YEAR_DESC = udc.ACADEMIC_YEAR_DESC
ORDER BY rcv.record_count_variance DESC