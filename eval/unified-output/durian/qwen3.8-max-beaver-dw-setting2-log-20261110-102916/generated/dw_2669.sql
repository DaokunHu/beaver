SELECT
    SPACE_UNIT.SPACE_UNIT AS department_name,
    AVG(SPACE_SUPERVISOR_USAGE.NUM_OF_SUPERVISEES) AS avg_supervisees,
    MAX(SPACE_SUPERVISOR_USAGE.NUM_OF_SUPERVISEES) - MIN(SPACE_SUPERVISOR_USAGE.NUM_OF_SUPERVISEES) AS supervisee_range,
    VARIANCE(SPACE_SUPERVISOR_USAGE.NUM_OF_SUPERVISEES) AS supervisee_variance,
    SUM(SPACE_SUPERVISOR_USAGE.SQFT) AS total_sqft,
    SUM(SPACE_SUPERVISOR_USAGE.RESEARCH_VOLUME) AS total_research_volume
FROM SPACE_SUPERVISOR_USAGE
JOIN SPACE_UNIT
    ON SPACE_SUPERVISOR_USAGE.DEPT_NAMES = SPACE_UNIT.DLC_KEY
GROUP BY SPACE_UNIT.SPACE_UNIT
ORDER BY supervisee_range DESC