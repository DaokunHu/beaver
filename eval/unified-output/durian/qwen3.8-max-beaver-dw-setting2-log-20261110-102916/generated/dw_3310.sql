WITH subq1 AS (
  SELECT t0.SUBJECT_TITLE,
         t1.DEPARTMENT_NAME,
         t1.SCHOOL_NAME,
         DENSE_RANK() OVER (ORDER BY t2.SUBJECT_CODE ROWS BETWEEN 2 PRECEDING AND CURRENT ROW) AS window_column
  FROM SUBJECT_OFFERED_SUMMARY t0
  JOIN SIS_COURSE_DESCRIPTION t1 ON t0.COURSE_NUMBER = t1.COURSE
  JOIN COURSE_CATALOG_SUBJECT_OFFERED t2 ON t1.COURSE = t2.SUBJECT_CODE
  WHERE t2.TERM_CODE = '2022FA' AND t0.TOTAL_UNITS = 12
),
subq2 AS (
  SELECT s.DEPARTMENT_NAME,
         s.SCHOOL_NAME,
         COUNT(l.LIBRARY_SUBJECT_OFFERED_KEY) AS offered_subject_count,
         MIN(l.NUM_ENROLLED_STUDENTS) AS min_enrolled_students
  FROM SIS_SUBJECT_CODE s
  JOIN LIBRARY_SUBJECT_OFFERED l ON s.COURSE_NUMBER = l.COURSE_NUMBER
  WHERE l.NUM_ENROLLED_STUDENTS > 3
  GROUP BY s.DEPARTMENT_NAME, s.SCHOOL_NAME
)
SELECT a.SUBJECT_TITLE,
       a.DEPARTMENT_NAME,
       a.window_column,
       b.offered_subject_count,
       b.min_enrolled_students
FROM subq1 a
JOIN subq2 b ON a.DEPARTMENT_NAME = b.DEPARTMENT_NAME AND a.SCHOOL_NAME = b.SCHOOL_NAME;