WITH inner_cte AS (
  SELECT t0.ACTIVITY_TITLE, t0.TERM_CODE, t0.MAX_ENROLLMENT, t1.TERM_DESCRIPTION, t1.TERM_START_DATE,
         t2.SUBJECT_TITLE, t2.NUM_ENROLLED_STUDENTS,
         ROW_NUMBER() OVER (PARTITION BY t2.SUBJECT_TITLE ORDER BY t0.ACTIVITY_TITLE) AS window_column
  FROM IAP_SUBJECT_DETAIL t0
  JOIN ACADEMIC_TERMS t1 ON t0.TERM_CODE = t1.TERM_CODE
  JOIN LIBRARY_SUBJECT_OFFERED t2 ON t1.TERM_CODE = t2.TERM_CODE
  WHERE t0.ENROLLMENT_TYPE = 'Advance sign-up required' AND t0.MAX_ENROLLMENT = 12
),
subq1 AS (
  SELECT inner_cte.ACTIVITY_TITLE, inner_cte.TERM_CODE, inner_cte.MAX_ENROLLMENT,
         inner_cte.TERM_DESCRIPTION, inner_cte.TERM_START_DATE,
         inner_cte.SUBJECT_TITLE, inner_cte.NUM_ENROLLED_STUDENTS,
         t2.OFFER_DEPT_NAME, t2.RESPONSIBLE_FACULTY_NAME, inner_cte.window_column
  FROM inner_cte
  JOIN LIBRARY_SUBJECT_OFFERED t2
    ON inner_cte.TERM_CODE = t2.TERM_CODE AND inner_cte.SUBJECT_TITLE = t2.SUBJECT_TITLE
  WHERE inner_cte.NUM_ENROLLED_STUDENTS >= 10
),
material_cte AS (
  SELECT IAP_SUBJECT_DETAIL.ACTIVITY_TITLE, ACADEMIC_TERMS.TERM_DESCRIPTION,
         COUNT(TIP_DETAIL.TIP_MATERIAL_KEY) AS material_count
  FROM IAP_SUBJECT_DETAIL
  JOIN ACADEMIC_TERMS ON IAP_SUBJECT_DETAIL.TERM_CODE = ACADEMIC_TERMS.TERM_CODE
  JOIN TIP_DETAIL ON ACADEMIC_TERMS.TERM_CODE = TIP_DETAIL.TERM_CODE
  WHERE IAP_SUBJECT_DETAIL.IS_CANCELLED = 'N'
  GROUP BY IAP_SUBJECT_DETAIL.ACTIVITY_TITLE, ACADEMIC_TERMS.TERM_DESCRIPTION
),
subq2 AS (
  SELECT ACTIVITY_TITLE, MAX(material_count) AS highest_material_count
  FROM material_cte
  GROUP BY ACTIVITY_TITLE
)
SELECT subq1.ACTIVITY_TITLE, subq1.TERM_CODE, subq1.MAX_ENROLLMENT,
       subq1.TERM_DESCRIPTION, subq1.TERM_START_DATE,
       subq1.SUBJECT_TITLE, subq1.NUM_ENROLLED_STUDENTS,
       subq1.OFFER_DEPT_NAME, subq1.RESPONSIBLE_FACULTY_NAME,
       subq1.window_column, subq2.highest_material_count
FROM subq1
JOIN subq2 ON subq1.ACTIVITY_TITLE = subq2.ACTIVITY_TITLE
ORDER BY subq1.SUBJECT_TITLE, subq1.ACTIVITY_TITLE