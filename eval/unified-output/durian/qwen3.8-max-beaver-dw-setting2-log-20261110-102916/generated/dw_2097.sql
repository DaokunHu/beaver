SELECT sd.DEPARTMENT_NAME,
       AVG(tso.NUM_ENROLLED_STUDENTS) AS avg_enrolled_students_per_subject
FROM TIP_SUBJECT_OFFERED tso
JOIN SIS_DEPARTMENT sd ON tso.OFFER_DEPT_CODE = sd.DEPARTMENT_CODE
WHERE tso.TERM_CODE = '2022FA'
  AND sd.IS_DEGREE_GRANTING = 'Y'
  AND sd.DEPARTMENT_CODE <> '6'
GROUP BY sd.DEPARTMENT_NAME
HAVING AVG(tso.NUM_ENROLLED_STUDENTS) > (
    SELECT AVG(t2.NUM_ENROLLED_STUDENTS)
    FROM TIP_SUBJECT_OFFERED t2
    JOIN SIS_DEPARTMENT sd2 ON t2.OFFER_DEPT_CODE = sd2.DEPARTMENT_CODE
    WHERE t2.TERM_CODE = '2022FA'
      AND sd2.IS_DEGREE_GRANTING = 'Y'
      AND sd2.DEPARTMENT_CODE <> '6'
)
ORDER BY sd.DEPARTMENT_NAME