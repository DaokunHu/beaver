SELECT t1.SUBJECT_CODE,
       t1.SUBJECT_CODE_DESC,
       t1.DEPARTMENT_NAME,
       t1.SCHOOL_NAME,
       t2.SUBJECT_TITLE,
       t2.NUM_ENROLLED_STUDENTS,
       ROW_NUMBER() OVER (PARTITION BY t1.DEPARTMENT_NAME ORDER BY t1.SUBJECT_CODE) AS window_column,
       cv.coefficient_of_variation
FROM SIS_SUBJECT_CODE t1
JOIN LIBRARY_SUBJECT_OFFERED t2
  ON t1.COURSE_NUMBER = t2.COURSE_NUMBER
JOIN (
    SELECT sd.DEPARTMENT_NAME,
           STDDEV_SAMP(tso.NUM_ENROLLED_STUDENTS) / NULLIF(AVG(tso.NUM_ENROLLED_STUDENTS), 0) AS coefficient_of_variation
    FROM SIS_DEPARTMENT sd
    JOIN TIP_SUBJECT_OFFERED tso
      ON sd.DEPARTMENT_CODE = tso.OFFER_DEPT_CODE
    WHERE sd.DEPARTMENT_NAME = 'Mathematics'
    GROUP BY sd.DEPARTMENT_NAME
) cv
  ON cv.DEPARTMENT_NAME = t1.DEPARTMENT_NAME
WHERE t2.TERM_CODE = '2014FA'
  AND t2.NUM_ENROLLED_STUDENTS > 5
  AND t1.DEPARTMENT_NAME = 'Mathematics'