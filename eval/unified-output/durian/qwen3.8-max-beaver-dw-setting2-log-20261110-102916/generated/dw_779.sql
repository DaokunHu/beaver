WITH RegularMathStats AS (
    SELECT
        ACADEMIC_TERMS.ACADEMIC_YEAR,
        ACADEMIC_TERMS.ACADEMIC_YEAR_DESC,
        AVG(COURSE_CATALOG_SUBJECT_OFFERED.TOTAL_UNITS) AS avg_total_units,
        STDDEV(COURSE_CATALOG_SUBJECT_OFFERED.TOTAL_UNITS) AS stddev_total_units
    FROM ACADEMIC_TERMS
    JOIN COURSE_CATALOG_SUBJECT_OFFERED
        ON ACADEMIC_TERMS.TERM_CODE = COURSE_CATALOG_SUBJECT_OFFERED.EFFECTIVE_TERM_CODE
    WHERE ACADEMIC_TERMS.IS_REGULAR_TERM = 'Y'
      AND COURSE_CATALOG_SUBJECT_OFFERED.DEPARTMENT_NAME = 'Mathematics'
    GROUP BY ACADEMIC_TERMS.ACADEMIC_YEAR, ACADEMIC_TERMS.ACADEMIC_YEAR_DESC
),
PreviousRegularVariance AS (
    SELECT
        ACADEMIC_TERMS.ACADEMIC_YEAR,
        ACADEMIC_TERMS.ACADEMIC_YEAR_DESC,
        VARIANCE(COURSE_CATALOG_SUBJECT_OFFERED.TOTAL_UNITS) AS total_units_variance
    FROM ACADEMIC_TERMS_ALL
    JOIN ACADEMIC_TERMS
        ON ACADEMIC_TERMS_ALL.TERM_CODE = ACADEMIC_TERMS.TERM_CODE
    JOIN COURSE_CATALOG_SUBJECT_OFFERED
        ON ACADEMIC_TERMS.TERM_CODE = COURSE_CATALOG_SUBJECT_OFFERED.TERM_CODE
    WHERE ACADEMIC_TERMS.IS_REGULAR_TERM = 'Y'
      AND ACADEMIC_TERMS.TERM_STATUS = 'Previous'
      AND COURSE_CATALOG_SUBJECT_OFFERED.DEPARTMENT_NAME = 'Mathematics'
    GROUP BY ACADEMIC_TERMS.ACADEMIC_YEAR, ACADEMIC_TERMS.ACADEMIC_YEAR_DESC
)
SELECT
    r.ACADEMIC_YEAR,
    r.ACADEMIC_YEAR_DESC,
    r.avg_total_units,
    r.stddev_total_units,
    p.total_units_variance
FROM RegularMathStats r
LEFT JOIN PreviousRegularVariance p
    ON r.ACADEMIC_YEAR = p.ACADEMIC_YEAR
   AND r.ACADEMIC_YEAR_DESC = p.ACADEMIC_YEAR_DESC
ORDER BY r.stddev_total_units DESC;