SELECT
    d.DEPARTMENT_NAME,
    AVG(t.NUM_ENROLLED_STUDENTS) AS avg_enrolled_students,
    VARIANCE(t.NUM_ENROLLED_STUDENTS) AS variance_enrolled_students,
    STDDEV(t.NUM_ENROLLED_STUDENTS) AS stddev_enrolled_students
FROM TIP_SUBJECT_OFFERED t
JOIN SIS_DEPARTMENT d
    ON t.OFFER_DEPT_CODE = d.DEPARTMENT_CODE
JOIN MIT_STUDENT_DIRECTORY s
    ON d.DEPARTMENT_CODE = s.DEPARTMENT
WHERE d.IS_DEGREE_GRANTING = 'Y'
  AND s.STUDENT_YEAR = '4'
  AND d.DEPARTMENT_NAME = 'Mathematics'
GROUP BY d.DEPARTMENT_NAME