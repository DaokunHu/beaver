WITH RoomStats AS (
  SELECT r.MAJOR_USE_DESC,
         o.ORGANIZATION_NAME,
         COUNT(r.FCLT_ROOM_KEY) AS room_count,
         MIN(r.FLOOR) AS min_floor
  FROM FCLT_ROOMS r
  JOIN FCLT_ORGANIZATION o ON r.FCLT_ORGANIZATION_KEY = o.FCLT_ORGANIZATION_KEY
  WHERE r.AREA > 100 AND r.ACCESS_LEVEL = 1
  GROUP BY r.MAJOR_USE_DESC, o.ORGANIZATION_NAME
),
OrgSuperviseeStats AS (
  SELECT o.ORGANIZATION_NAME,
         EXP(AVG(LN(su.NUM_OF_SUPERVISEES))) AS geometric_mean_supervisees
  FROM FCLT_ORGANIZATION o
  JOIN SPACE_UNIT u ON o.DLC_KEY = u.DLC_KEY
  JOIN SPACE_SUPERVISOR_USAGE su ON u.DLC_KEY = su.DEPT_NAMES
  WHERE su.NUM_OF_SUPERVISEES > 0
  GROUP BY o.ORGANIZATION_NAME
),
OrgResearchStats AS (
  SELECT o.ORGANIZATION_NAME,
         SUM(su.RESEARCH_VOLUME) AS total_research_volume
  FROM FCLT_ORGANIZATION o
  JOIN SPACE_UNIT u ON o.DLC_KEY = u.DLC_KEY
  JOIN SPACE_SUPERVISOR_USAGE su ON u.DLC_KEY = su.DEPT_NAMES
  WHERE su.RESEARCH_VOLUME > 0
  GROUP BY o.ORGANIZATION_NAME
)
SELECT rs.MAJOR_USE_DESC,
       rs.ORGANIZATION_NAME,
       rs.room_count,
       rs.min_floor,
       os.geometric_mean_supervisees,
       ors.total_research_volume
FROM RoomStats rs
LEFT JOIN OrgSuperviseeStats os ON rs.ORGANIZATION_NAME = os.ORGANIZATION_NAME
LEFT JOIN OrgResearchStats ors ON rs.ORGANIZATION_NAME = ors.ORGANIZATION_NAME