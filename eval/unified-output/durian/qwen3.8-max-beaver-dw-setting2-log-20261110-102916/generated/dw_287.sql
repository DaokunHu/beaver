SELECT t0.DEPARTMENT_NAME,
       t1.SUBJECT_TITLE,
       t1.NUM_ENROLLED_STUDENTS,
       t2.SCHOOL_NAME,
       DENSE_RANK() OVER (PARTITION BY t0.DEPARTMENT_CODE ORDER BY t0.DEPARTMENT_CODE) AS window_column
FROM SIS_DEPARTMENT t0
JOIN TIP_SUBJECT_OFFERED t1 ON t0.DEPARTMENT_CODE = t1.OFFER_DEPT_CODE
JOIN STUDENT_DEPARTMENT t2 ON t1.OFFER_DEPT_CODE = t2.DEPARTMENT_CODE
WHERE t1.NUM_ENROLLED_STUDENTS > 0
  AND t0.IS_DEGREE_GRANTING = 'Y'
  AND t0.DEPARTMENT_NAME = 'Mathematics'
  AND t0.DEPARTMENT_CODE = '18'
  AND t1.NUM_ENROLLED_STUDENTS > (
        SELECT AVG(t3.NUM_ENROLLED_STUDENTS)
        FROM TIP_SUBJECT_OFFERED t3
        WHERE t3.OFFER_DEPT_CODE = '18'
      )