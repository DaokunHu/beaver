SELECT
  CASE WHEN GROUPING(t.DEPARTMENT_NAME) = 1 THEN NULL ELSE t.DEPARTMENT_NAME END AS DEPARTMENT_NAME,
  t.SCHOOL_NAME,
  CASE WHEN GROUPING(t.DEPARTMENT_NAME) = 1 THEN NULL ELSE t.TERM_START_DATE END AS TERM_START_DATE,
  SUM(t.max_enrollment) AS max_enrollment
FROM (
  SELECT
    ss.DEPARTMENT_NAME,
    ss.SCHOOL_NAME,
    at.TERM_START_DATE,
    MAX(ss.SUBJECT_ENROLLMENT_NUMBER) AS max_enrollment
  FROM ACADEMIC_TERM_PARAMETER atp
  JOIN ACADEMIC_TERMS at ON atp.TERM_CODE = at.TERM_CODE
  JOIN SUBJECT_SUMMARY ss ON at.TERM_CODE = ss.TERM_CODE
  WHERE atp.IS_CURRENT_TERM = 'Y'
  GROUP BY ss.DEPARTMENT_NAME, ss.SCHOOL_NAME, at.TERM_START_DATE
  HAVING MAX(ss.SUBJECT_ENROLLMENT_NUMBER) > 5
) t
GROUP BY t.SCHOOL_NAME, t.DEPARTMENT_NAME, t.TERM_START_DATE WITH ROLLUP
HAVING (GROUPING(t.DEPARTMENT_NAME) = 0 AND GROUPING(t.TERM_START_DATE) = 0)
    OR (GROUPING(t.DEPARTMENT_NAME) = 1 AND GROUPING(t.SCHOOL_NAME) = 0)