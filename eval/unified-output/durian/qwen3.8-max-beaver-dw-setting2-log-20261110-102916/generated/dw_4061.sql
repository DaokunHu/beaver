WITH dept_units AS (
  SELECT ACADEMIC_TERMS.ACADEMIC_YEAR,
         ACADEMIC_TERMS.ACADEMIC_YEAR_DESC,
         EXP(AVG(LN(COURSE_CATALOG_SUBJECT_OFFERED.TOTAL_UNITS))) AS geometric_mean_total_units,
         COURSE_CATALOG_SUBJECT_OFFERED.DEPARTMENT_NAME
  FROM ACADEMIC_TERMS
  JOIN COURSE_CATALOG_SUBJECT_OFFERED
    ON ACADEMIC_TERMS.TERM_CODE = COURSE_CATALOG_SUBJECT_OFFERED.EFFECTIVE_TERM_CODE
  WHERE ACADEMIC_TERMS.IS_REGULAR_TERM = 'Y'
    AND COURSE_CATALOG_SUBJECT_OFFERED.TOTAL_UNITS > 0
  GROUP BY ACADEMIC_TERMS.ACADEMIC_YEAR, ACADEMIC_TERMS.ACADEMIC_YEAR_DESC, COURSE_CATALOG_SUBJECT_OFFERED.DEPARTMENT_NAME
), building_stats AS (
  SELECT b.BUILDING_NAME,
         AVG(r.AREA) AS avg_room_area,
         MAX(r.AREA) - MIN(r.AREA) AS room_area_range,
         VARIANCE(r.AREA) AS room_area_variance
  FROM FCLT_ROOMS r
  JOIN FCLT_BUILDING b ON r.FCLT_BUILDING_KEY = b.FCLT_BUILDING_KEY
  WHERE b.BUILDING_TYPE = 'ACADEMIC' AND r.AREA > 40
  GROUP BY b.BUILDING_NAME
)
SELECT ds.DEPARTMENT_NAME,
       ds.ACADEMIC_YEAR,
       ds.ACADEMIC_YEAR_DESC,
       ds.geometric_mean_total_units,
       bs.BUILDING_NAME,
       bs.avg_room_area,
       bs.room_area_range,
       bs.room_area_variance,
       fb.ASSIGNABLE_AREA,
       fb.DATE_BUILT
FROM dept_units ds
JOIN COURSE_CATALOG_SUBJECT_OFFERED cso
  ON ds.DEPARTMENT_NAME = cso.DEPARTMENT_NAME
 AND ds.ACADEMIC_YEAR = cso.ACADEMIC_YEAR
JOIN FCLT_ROOMS fr ON cso.MEET_PLACE = fr.FCLT_ROOM_KEY
JOIN FCLT_BUILDING fb ON fr.FCLT_BUILDING_KEY = fb.FCLT_BUILDING_KEY
JOIN building_stats bs ON fb.BUILDING_NAME = bs.BUILDING_NAME
ORDER BY ds.DEPARTMENT_NAME, ds.ACADEMIC_YEAR DESC, bs.room_area_range DESC;