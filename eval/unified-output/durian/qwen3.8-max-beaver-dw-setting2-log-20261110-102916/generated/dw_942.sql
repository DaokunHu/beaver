WITH units_stats AS (
    SELECT ACADEMIC_TERMS_ALL.ACADEMIC_YEAR,
           COURSE_CATALOG_SUBJECT_OFFERED.DEPARTMENT_NAME,
           VARIANCE(SUBJECT_SUMMARY.TOTAL_UNITS) AS total_units_variance,
           STDDEV(SUBJECT_SUMMARY.TOTAL_UNITS) AS total_units_stddev
    FROM COURSE_CATALOG_SUBJECT_OFFERED
    JOIN ACADEMIC_TERMS_ALL ON COURSE_CATALOG_SUBJECT_OFFERED.TERM_CODE = ACADEMIC_TERMS_ALL.TERM_CODE
    JOIN SUBJECT_SUMMARY ON ACADEMIC_TERMS_ALL.TERM_CODE = SUBJECT_SUMMARY.TERM_CODE
    WHERE ACADEMIC_TERMS_ALL.IS_CURRENT_TERM = 'Y'
      AND SUBJECT_SUMMARY.TOTAL_UNITS > 0
      AND COURSE_CATALOG_SUBJECT_OFFERED.DEPARTMENT_NAME = 'Mathematics'
    GROUP BY ACADEMIC_TERMS_ALL.ACADEMIC_YEAR, COURSE_CATALOG_SUBJECT_OFFERED.DEPARTMENT_NAME
),
ccc_stats AS (
    SELECT sd.DEPARTMENT_NAME,
           AVG(sad.CLEARING_COST_COLLECTOR) AS avg_clearing_cost_collector,
           STDDEV(sad.CLEARING_COST_COLLECTOR) AS stddev_clearing_cost_collector
    FROM SIS_DEPARTMENT sd
    JOIN SIS_ADMIN_DEPARTMENT sad ON sd.DEPARTMENT_CODE = sad.SIS_ADMIN_DEPARTMENT_CODE
    WHERE sd.IS_DEGREE_GRANTING = 'Y'
      AND sd.DEPARTMENT_CODE <> '17'
    GROUP BY sd.DEPARTMENT_NAME
)
SELECT us.ACADEMIC_YEAR,
       us.DEPARTMENT_NAME,
       us.total_units_variance,
       us.total_units_stddev,
       cs.avg_clearing_cost_collector,
       cs.stddev_clearing_cost_collector
FROM units_stats us
JOIN ccc_stats cs ON us.DEPARTMENT_NAME = cs.DEPARTMENT_NAME
ORDER BY us.total_units_variance DESC