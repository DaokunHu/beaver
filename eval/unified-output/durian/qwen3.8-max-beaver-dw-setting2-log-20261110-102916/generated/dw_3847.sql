WITH part1 AS (
  SELECT t0.SUBJECT_CODE,
         t0.SUBJECT_NUMBER,
         t0.SUBJECT_TITLE,
         t0.DEPARTMENT_NAME,
         t1.TERM_DESCRIPTION,
         RANK() OVER (PARTITION BY t0.DEPARTMENT_NAME ORDER BY t0.SUBJECT_CODE) AS dept_rank
  FROM COURSE_CATALOG_SUBJECT_OFFERED t0
  JOIN ACADEMIC_TERMS t1 ON t0.EFFECTIVE_TERM_CODE = t1.TERM_CODE
  JOIN SUBJECT_SUMMARY t2 ON t1.TERM_CODE = t2.TERM_CODE
  WHERE t0.ACADEMIC_YEAR = 2024
    AND t0.TOTAL_UNITS = 12
),
part2 AS (
  SELECT tso.OFFER_DEPT_NAME,
         AVG(sos.TOTAL_UNITS) AS avg_total_units,
         MAX(sos.TOTAL_UNITS) - MIN(sos.TOTAL_UNITS) AS total_units_range,
         VARIANCE(sos.TOTAL_UNITS) AS total_units_variance
  FROM TIP_SUBJECT_OFFERED tso
  JOIN TIP_DETAIL td ON tso.SUBJECT_ID = td.SUBJECT_ID
  JOIN SUBJECT_OFFERED_SUMMARY sos ON td.SUBJECT_ID = sos.SUBJECT_ID
  WHERE tso.NUM_ENROLLED_STUDENTS > 0
    AND td.TIP_MATERIAL_STATUS_KEY = 'RQ'
  GROUP BY tso.OFFER_DEPT_NAME
)
SELECT p1.SUBJECT_CODE,
       p1.SUBJECT_NUMBER,
       p1.SUBJECT_TITLE,
       p1.DEPARTMENT_NAME,
       p1.TERM_DESCRIPTION,
       p1.dept_rank,
       p2.avg_total_units,
       p2.total_units_range,
       p2.total_units_variance
FROM part1 p1
JOIN part2 p2 ON p1.DEPARTMENT_NAME = p2.OFFER_DEPT_NAME
ORDER BY p1.DEPARTMENT_NAME, p1.SUBJECT_CODE