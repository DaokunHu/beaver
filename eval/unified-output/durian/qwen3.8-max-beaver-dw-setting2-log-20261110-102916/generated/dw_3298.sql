WITH Sub1 AS (
    SELECT t0.SUBJECT_TITLE,
           t0.NUM_ENROLLED_STUDENTS,
           t0.OFFER_DEPT_NAME,
           t1.TERM_DESCRIPTION,
           t1.ACADEMIC_YEAR,
           t2.SUBJECT_SHORT_TITLE,
           MAX(t2.TOTAL_UNITS) OVER (ORDER BY t0.SUBJECT_ID ROWS BETWEEN CURRENT ROW AND 2 FOLLOWING) AS max_total_units
    FROM LIBRARY_SUBJECT_OFFERED t0
    JOIN ACADEMIC_TERMS t1 ON t0.TERM_CODE = t1.TERM_CODE
    JOIN COURSE_CATALOG_SUBJECT_OFFERED t2 ON t1.TERM_CODE = t2.TERM_CODE AND t0.SUBJECT_ID = t2.SUBJECT_ID
    WHERE t0.OFFER_DEPT_NAME = 'Mathematics'
      AND t1.IS_REGULAR_TERM = 'Y'
),
Sub2 AS (
    SELECT d.DEPARTMENT_NAME,
           AVG(c.CIP_PROGRAM_CODE) AS avg_cip_code,
           MAX(c.CIP_PROGRAM_CODE) - MIN(c.CIP_PROGRAM_CODE) AS cip_code_range,
           VARIANCE(c.CIP_PROGRAM_CODE) AS cip_code_variance
    FROM SIS_COURSE_DESCRIPTION c
    JOIN SIS_DEPARTMENT d ON c.DEPARTMENT = d.DEPARTMENT_CODE
    WHERE d.IS_DEGREE_GRANTING = 'Y'
      AND c.COURSE_LEVEL = 'U'
    GROUP BY d.DEPARTMENT_NAME
)
SELECT s1.SUBJECT_TITLE,
       s1.NUM_ENROLLED_STUDENTS,
       s1.OFFER_DEPT_NAME,
       s1.TERM_DESCRIPTION,
       s1.ACADEMIC_YEAR,
       s1.SUBJECT_SHORT_TITLE,
       s1.max_total_units,
       s2.avg_cip_code,
       s2.cip_code_range,
       s2.cip_code_variance
FROM Sub1 s1
JOIN Sub2 s2 ON s1.OFFER_DEPT_NAME = s2.DEPARTMENT_NAME