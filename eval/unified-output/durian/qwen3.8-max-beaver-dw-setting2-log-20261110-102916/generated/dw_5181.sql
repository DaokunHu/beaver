SELECT
    sd.DEPARTMENT_FULL_NAME,
    MAX(ccso.TOTAL_UNITS) - MIN(ccso.TOTAL_UNITS) AS range_total_units,
    VARIANCE(ccso.TOTAL_UNITS) AS variance_total_units
FROM SIS_COURSE_DESCRIPTION scd
JOIN SIS_DEPARTMENT sd
    ON scd.DEPARTMENT = sd.DEPARTMENT_CODE
JOIN COURSE_CATALOG_SUBJECT_OFFERED ccso
    ON sd.DEPARTMENT_CODE = ccso.DEPARTMENT_CODE
WHERE ccso.ACADEMIC_YEAR = 2024
  AND sd.IS_DEGREE_GRANTING = 'Y'
  AND sd.DEPARTMENT_CODE <> '7'
GROUP BY sd.DEPARTMENT_FULL_NAME