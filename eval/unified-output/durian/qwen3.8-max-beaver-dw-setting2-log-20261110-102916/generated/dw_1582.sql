WITH inner_cte AS (
  SELECT t1.SUBJECT_CODE, t1.SUBJECT_TITLE, t1.DEPARTMENT_NAME, t0.SCHOOL_NAME
  FROM SIS_DEPARTMENT t0
  JOIN COURSE_CATALOG_SUBJECT_OFFERED t1 ON t0.DEPARTMENT_CODE = t1.DEPARTMENT_CODE
  WHERE t1.ACADEMIC_YEAR = 2024 AND t1.TOTAL_UNITS = 12 AND t1.DEPARTMENT_NAME = 'Mathematics'
),
school_counts AS (
  SELECT SCHOOL_NAME, COUNT(*) AS subject_count
  FROM inner_cte
  GROUP BY SCHOOL_NAME
  HAVING COUNT(*) >= 2
),
dept_stats AS (
  SELECT sd.DEPARTMENT_NAME, sd.SCHOOL_NAME,
         VARIANCE(ccc.TOTAL_UNITS) AS variance_total_units,
         STDDEV(ccc.TOTAL_UNITS) AS stddev_total_units
  FROM SIS_DEPARTMENT sd
  JOIN CIS_COURSE_CATALOG ccc ON sd.DEPARTMENT_CODE = ccc.DEPARTMENT_CODE
  WHERE sd.IS_DEGREE_GRANTING = 'Y' AND ccc.TOTAL_UNITS IS NOT NULL
  GROUP BY sd.DEPARTMENT_NAME, sd.SCHOOL_NAME
)
SELECT ic.SUBJECT_CODE, ic.SUBJECT_TITLE, ic.DEPARTMENT_NAME, ic.SCHOOL_NAME,
       sc.subject_count, ds.variance_total_units, ds.stddev_total_units
FROM inner_cte ic
JOIN school_counts sc ON ic.SCHOOL_NAME = sc.SCHOOL_NAME
JOIN dept_stats ds ON ic.DEPARTMENT_NAME = ds.DEPARTMENT_NAME AND ic.SCHOOL_NAME = ds.SCHOOL_NAME
ORDER BY ic.SCHOOL_NAME, ic.SUBJECT_CODE