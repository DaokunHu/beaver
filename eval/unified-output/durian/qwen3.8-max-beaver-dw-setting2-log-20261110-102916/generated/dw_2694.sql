SELECT so.SUBJECT_KEY,
       so.SUBJECT_TITLE,
       ss.DEPARTMENT_NAME,
       COUNT(so.SUBJECT_KEY) AS offering_count,
       SUM(sos.TOTAL_UNITS) AS total_units,
       SUM(so.NUM_ENROLLED_STUDENTS) AS total_enrolled_students
FROM SUBJECT_OFFERED_SUMMARY sos
JOIN SUBJECT_OFFERED so ON sos.SUBJECT_ID = so.SUBJECT_ID
JOIN SUBJECT_SUMMARY ss ON so.SUBJECT_ID = ss.SUBJECT_ID
WHERE so.TERM_CODE = '2012SU'
  AND ss.DEPARTMENT_NAME = 'Harvard Cross-Enrollment Prog'
GROUP BY so.SUBJECT_KEY, so.SUBJECT_TITLE, ss.DEPARTMENT_NAME