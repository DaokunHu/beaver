SELECT
    subq1.OFFER_DEPT_NAME,
    subq1.ACADEMIC_YEAR,
    subq1.subject_count,
    subq1.min_term_start_date,
    subq2.SUBJECT_TITLE,
    subq2.NUM_ENROLLED_STUDENTS,
    subq2.RESPONSIBLE_FACULTY_NAME,
    subq2.OFFER_DEPT_NAME,
    subq2.DEPARTMENT_FULL_NAME,
    subq2.SCHOOL_NAME,
    subq2.window_column
FROM (
    SELECT
        lso.OFFER_DEPT_NAME,
        at.ACADEMIC_YEAR,
        COUNT(DISTINCT so.SUBJECT_ID) AS subject_count,
        MIN(at.TERM_START_DATE) AS min_term_start_date
    FROM LIBRARY_SUBJECT_OFFERED lso
    JOIN ACADEMIC_TERMS at ON lso.TERM_CODE = at.TERM_CODE
    JOIN SUBJECT_OFFERED so ON at.TERM_CODE = so.TERM_CODE
    WHERE lso.NUM_ENROLLED_STUDENTS > 3
    GROUP BY lso.OFFER_DEPT_NAME, at.ACADEMIC_YEAR
) subq1
JOIN (
    SELECT
        t0.SUBJECT_TITLE,
        t0.NUM_ENROLLED_STUDENTS,
        t0.RESPONSIBLE_FACULTY_NAME,
        t0.OFFER_DEPT_NAME,
        t1.DEPARTMENT_FULL_NAME,
        t1.SCHOOL_NAME,
        MIN(t0.NUM_ENROLLED_STUDENTS) OVER (ORDER BY t1.DEPARTMENT_CODE ROWS BETWEEN 3 PRECEDING AND 1 FOLLOWING) AS window_column
    FROM TIP_SUBJECT_OFFERED t0
    JOIN STUDENT_DEPARTMENT t1 ON t0.OFFER_DEPT_CODE = t1.DEPARTMENT_CODE
    WHERE t0.TERM_CODE = '2017JA'
) subq2 ON subq1.OFFER_DEPT_NAME = subq2.OFFER_DEPT_NAME