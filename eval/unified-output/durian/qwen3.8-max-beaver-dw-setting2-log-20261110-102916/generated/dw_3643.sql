WITH subq1 AS (
  SELECT t0.SUBJECT_ID,
         t0.SUBJECT_TITLE,
         t0.NUM_ENROLLED_STUDENTS,
         t1.DEPARTMENT_NAME,
         t1.DEPARTMENT_FULL_NAME,
         ROW_NUMBER() OVER (PARTITION BY t1.DEPARTMENT_NAME ORDER BY t0.SUBJECT_ID) AS window_column
  FROM TIP_SUBJECT_OFFERED t0
  JOIN SIS_DEPARTMENT t1 ON t0.OFFER_DEPT_CODE = t1.DEPARTMENT_CODE
  WHERE t0.TERM_CODE = '2019FA'
),
subq2 AS (
  SELECT t1.SUBJECT_TITLE,
         t1.DEPARTMENT_NAME,
         t1.TOTAL_UNITS,
         ROW_NUMBER() OVER (ORDER BY t1.SUBJECT_TITLE ROWS BETWEEN 2 PRECEDING AND 1 FOLLOWING) AS window_column
  FROM ACADEMIC_TERMS t0
  JOIN SUBJECT_SUMMARY t1 ON t0.TERM_CODE = t1.TERM_CODE
  WHERE t0.TERM_CODE = '2009SP'
)
SELECT s1.SUBJECT_ID,
       s1.SUBJECT_TITLE,
       s1.NUM_ENROLLED_STUDENTS,
       s1.DEPARTMENT_NAME,
       s1.DEPARTMENT_FULL_NAME,
       s1.window_column AS row_number_2019fa,
       s2.TOTAL_UNITS,
       s2.window_column AS row_number_2009sp
FROM subq1 s1
JOIN subq2 s2
  ON s1.SUBJECT_TITLE = s2.SUBJECT_TITLE
 AND s1.DEPARTMENT_NAME = s2.DEPARTMENT_NAME