SELECT
    t1.ACADEMIC_YEAR,
    t1.ACADEMIC_YEAR_DESC,
    AVG(t0.TOTAL_UNITS) AS avg_total_units,
    STDDEV(t0.TOTAL_UNITS) AS stddev_total_units
FROM COURSE_CATALOG_SUBJECT_OFFERED t0
JOIN ACADEMIC_TERMS_ALL t1
    ON t0.TERM_CODE = t1.TERM_CODE
JOIN TIP_DETAIL t2
    ON t1.TERM_CODE = t2.TERM_CODE
    AND t0.SUBJECT_ID = t2.SUBJECT_ID
WHERE t0.DEPARTMENT_NAME = 'Mathematics'
    AND t2.TIP_MATERIAL_STATUS_KEY IN ('RQ', 'EO')
GROUP BY t1.ACADEMIC_YEAR, t1.ACADEMIC_YEAR_DESC
ORDER BY t1.ACADEMIC_YEAR