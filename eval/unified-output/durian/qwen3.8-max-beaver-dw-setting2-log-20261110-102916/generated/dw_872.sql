SELECT t0.SUBJECT_ID,
       t0.SUBJECT_CODE,
       t0.SUBJECT_NUMBER,
       t0.DEPARTMENT_NAME,
       t0.SUBJECT_SHORT_TITLE,
       t0.SUBJECT_TITLE,
       t0.LECTURE_UNITS,
       t0.LAB_UNITS,
       t0.TOTAL_UNITS,
       t0.GRADE_TYPE,
       t0.GRADE_RULE,
       MIN(t0.TOTAL_UNITS) OVER (PARTITION BY t0.DEPARTMENT_CODE ORDER BY t0.DEPARTMENT_CODE) AS min_total_units_by_dept,
       gm.geometric_mean_total_units
FROM COURSE_CATALOG_SUBJECT_OFFERED t0
JOIN CIS_COURSE_CATALOG t1 ON t0.SUBJECT_ID = t1.SUBJECT_ID
JOIN (
    SELECT scd.DEPARTMENT_NAME,
           EXP(AVG(LN(ccso.TOTAL_UNITS))) AS geometric_mean_total_units
    FROM SIS_COURSE_DESCRIPTION scd
    JOIN COURSE_CATALOG_SUBJECT_OFFERED ccso ON scd.COURSE = ccso.SUBJECT_CODE
    WHERE ccso.IS_OFFERED_THIS_YEAR = 'Y'
      AND ccso.TOTAL_UNITS > 0
      AND scd.DEPARTMENT_NAME = 'Mathematics'
    GROUP BY scd.DEPARTMENT_NAME
) gm ON gm.DEPARTMENT_NAME = t0.DEPARTMENT_NAME
WHERE t0.ACADEMIC_YEAR = 2024
  AND t0.DEPARTMENT_NAME = 'Mathematics'
ORDER BY t0.DEPARTMENT_NAME, t0.SUBJECT_CODE