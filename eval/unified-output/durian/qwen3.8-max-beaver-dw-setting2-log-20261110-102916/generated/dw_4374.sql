SELECT
  c1.DEPARTMENT_NAME,
  NULL AS ACADEMIC_YEAR,
  NULL AS ACADEMIC_YEAR_DESC,
  c1.subject_count,
  c1.avg_total_units,
  c1.total_units_range,
  c1.total_units_variance,
  NULL AS coefficient_of_variation,
  '2022 Degree-Granting Subjects' AS reason
FROM (
  SELECT
    SIS_COURSE_DESCRIPTION.DEPARTMENT_NAME,
    COUNT(*) AS subject_count,
    AVG(COURSE_CATALOG_SUBJECT_OFFERED.TOTAL_UNITS) AS avg_total_units,
    MAX(COURSE_CATALOG_SUBJECT_OFFERED.TOTAL_UNITS) - MIN(COURSE_CATALOG_SUBJECT_OFFERED.TOTAL_UNITS) AS total_units_range,
    VARIANCE(COURSE_CATALOG_SUBJECT_OFFERED.TOTAL_UNITS) AS total_units_variance
  FROM SIS_SUBJECT_CODE
  JOIN SIS_COURSE_DESCRIPTION ON SIS_SUBJECT_CODE.COURSE_NUMBER = SIS_COURSE_DESCRIPTION.COURSE
  JOIN COURSE_CATALOG_SUBJECT_OFFERED ON SIS_COURSE_DESCRIPTION.COURSE = COURSE_CATALOG_SUBJECT_OFFERED.SUBJECT_CODE
  WHERE COURSE_CATALOG_SUBJECT_OFFERED.ACADEMIC_YEAR = 2022
    AND SIS_COURSE_DESCRIPTION.IS_DEGREE_GRANTING = 'Y'
  GROUP BY SIS_COURSE_DESCRIPTION.DEPARTMENT_NAME
  HAVING COUNT(*) >= 5
) c1
UNION ALL
SELECT
  c2.DEPARTMENT_NAME,
  c2.ACADEMIC_YEAR,
  c2.ACADEMIC_YEAR_DESC,
  NULL AS subject_count,
  NULL AS avg_total_units,
  NULL AS total_units_range,
  NULL AS total_units_variance,
  c2.coefficient_of_variation,
  'Library Reserve Materials' AS reason
FROM (
  SELECT
    COURSE_CATALOG_SUBJECT_OFFERED.DEPARTMENT_NAME,
    ACADEMIC_TERMS_ALL.ACADEMIC_YEAR,
    ACADEMIC_TERMS_ALL.ACADEMIC_YEAR_DESC,
    STDDEV(COURSE_CATALOG_SUBJECT_OFFERED.TOTAL_UNITS) / NULLIF(AVG(COURSE_CATALOG_SUBJECT_OFFERED.TOTAL_UNITS), 0) AS coefficient_of_variation
  FROM LIBRARY_RESERVE_MATRL_DETAIL
  JOIN ACADEMIC_TERMS_ALL ON LIBRARY_RESERVE_MATRL_DETAIL.TERM_CODE = ACADEMIC_TERMS_ALL.TERM_CODE
  JOIN COURSE_CATALOG_SUBJECT_OFFERED ON ACADEMIC_TERMS_ALL.TERM_CODE = COURSE_CATALOG_SUBJECT_OFFERED.TERM_CODE
  WHERE LIBRARY_RESERVE_MATRL_DETAIL.LIBRARY_MATERIAL_STATUS_KEY = 'U'
  GROUP BY ACADEMIC_TERMS_ALL.ACADEMIC_YEAR, ACADEMIC_TERMS_ALL.ACADEMIC_YEAR_DESC, COURSE_CATALOG_SUBJECT_OFFERED.DEPARTMENT_NAME
  HAVING AVG(COURSE_CATALOG_SUBJECT_OFFERED.TOTAL_UNITS) > 0
) c2