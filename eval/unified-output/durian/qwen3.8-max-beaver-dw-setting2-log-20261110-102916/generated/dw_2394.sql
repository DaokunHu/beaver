WITH Sub2 AS (
  SELECT sd.DEPARTMENT_NAME,
         MAX(scd.CIP_PROGRAM_CODE) AS MAX_CIP_PROGRAM_CODE,
         sd.DEPARTMENT_FULL_NAME
  FROM SIS_DEPARTMENT sd
  JOIN SIS_COURSE_DESCRIPTION scd ON sd.DEPARTMENT_CODE = scd.DEPARTMENT
  WHERE sd.IS_DEGREE_GRANTING = 'Y'
    AND sd.DEPARTMENT_NAME <> 'Mathematics'
    AND scd.CIP_PROGRAM_CODE > 120000
  GROUP BY sd.DEPARTMENT_NAME, sd.DEPARTMENT_FULL_NAME
),
inner_cte AS (
  SELECT tso.TERM_CODE,
         tso.OFFER_DEPT_NAME,
         tso.NUM_ENROLLED_STUDENTS,
         s2.MAX_CIP_PROGRAM_CODE,
         s2.DEPARTMENT_FULL_NAME
  FROM TIP_SUBJECT_OFFERED tso
  JOIN TIP_DETAIL td ON tso.SUBJECT_ID = td.SUBJECT_ID
  JOIN Sub2 s2 ON tso.OFFER_DEPT_NAME = s2.DEPARTMENT_NAME
  WHERE tso.OFFER_DEPT_NAME = 'Chemistry'
    AND td.TIP_MATERIAL_STATUS_KEY IS NOT NULL
)
SELECT CASE WHEN LAG(term) OVER (ORDER BY term_sort, term, dept_sort) = term THEN NULL ELSE term END AS term,
       dept,
       avg_enrolled_students,
       stddev_enrolled_students,
       MAX_CIP_PROGRAM_CODE,
       DEPARTMENT_FULL_NAME
FROM (
  SELECT CASE WHEN GROUPING(TERM_CODE) = 1 AND GROUPING(OFFER_DEPT_NAME) = 1 THEN 'zzz' ELSE TERM_CODE END AS term_sort,
         CASE WHEN GROUPING(TERM_CODE) = 0 AND GROUPING(OFFER_DEPT_NAME) = 1 THEN 'SUBTOTAL'
              WHEN GROUPING(TERM_CODE) = 1 AND GROUPING(OFFER_DEPT_NAME) = 1 THEN 'TOTAL'
              ELSE TERM_CODE END AS term,
         CASE WHEN GROUPING(TERM_CODE) = 0 AND GROUPING(OFFER_DEPT_NAME) = 1 THEN 'zzz' ELSE OFFER_DEPT_NAME END AS dept_sort,
         OFFER_DEPT_NAME AS dept,
         AVG(NUM_ENROLLED_STUDENTS) AS avg_enrolled_students,
         STDDEV(NUM_ENROLLED_STUDENTS) AS stddev_enrolled_students,
         MAX(MAX_CIP_PROGRAM_CODE) AS MAX_CIP_PROGRAM_CODE,
         MAX(DEPARTMENT_FULL_NAME) AS DEPARTMENT_FULL_NAME
  FROM inner_cte
  GROUP BY TERM_CODE, OFFER_DEPT_NAME WITH ROLLUP
) tbltmp
ORDER BY term_sort, dept_sort