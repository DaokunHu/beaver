SELECT t2.SUBJECT_ID,
       t0.TERM_DESCRIPTION,
       t2.TIP_MATERIAL_STATUS_KEY,
       t1.ACADEMIC_YEAR,
       t3.DEPARTMENT_NAME,
       RANK() OVER (PARTITION BY t1.ACADEMIC_YEAR ORDER BY t2.SUBJECT_ID) AS window_column
FROM ACADEMIC_TERMS_ALL t0
JOIN ACADEMIC_TERMS t1 ON t0.TERM_CODE = t1.TERM_CODE
JOIN TIP_DETAIL t2 ON t1.TERM_CODE = t2.TERM_CODE
JOIN SIS_DEPARTMENT t3 ON SUBSTRING_INDEX(t2.SUBJECT_ID, '.', 1) = t3.DEPARTMENT_CODE
WHERE t2.TERM_CODE = '2010FA'