WITH inner_cte AS (
  SELECT t0.COURSE_NUMBER, t0.SUBJECT_TITLE, t0.NUM_ENROLLED_STUDENTS,
         t1.TERM_DESCRIPTION, t1.ACADEMIC_YEAR,
         ROW_NUMBER() OVER (PARTITION BY t1.ACADEMIC_YEAR ORDER BY t0.COURSE_NUMBER) AS window_column
  FROM LIBRARY_SUBJECT_OFFERED t0
  JOIN ACADEMIC_TERMS t1 ON t0.TERM_CODE = t1.TERM_CODE
  WHERE t0.OFFER_DEPT_NAME = 'Mathematics' AND t0.NUM_ENROLLED_STUDENTS >= 5
),
avg_enrollment AS (
  SELECT t1.ACADEMIC_YEAR, AVG(t0.NUM_ENROLLED_STUDENTS) AS avg_students
  FROM LIBRARY_SUBJECT_OFFERED t0
  JOIN ACADEMIC_TERMS t1 ON t0.TERM_CODE = t1.TERM_CODE
  WHERE t0.OFFER_DEPT_NAME = 'Mathematics' AND t0.NUM_ENROLLED_STUDENTS >= 5
  GROUP BY t1.ACADEMIC_YEAR
),
math_courses AS (
  SELECT i.COURSE_NUMBER, i.SUBJECT_TITLE, i.NUM_ENROLLED_STUDENTS,
         i.TERM_DESCRIPTION, i.ACADEMIC_YEAR, i.window_column
  FROM inner_cte i
  JOIN avg_enrollment a ON i.ACADEMIC_YEAR = a.ACADEMIC_YEAR
  WHERE i.NUM_ENROLLED_STUDENTS > a.avg_students
),
subject_stats AS (
  SELECT d.DEPARTMENT_CODE, d.DEPARTMENT_NAME, s.SUBJECT_CODE, s.SUBJECT_CODE_DESC,
         AVG(ASCII(s.COURSE_NUMBER)) AS avg_course_number_ascii,
         VARIANCE(ASCII(s.COURSE_NUMBER)) AS var_course_number_ascii
  FROM SIS_DEPARTMENT d
  JOIN SIS_SUBJECT_CODE s ON d.DEPARTMENT_CODE = s.DEPARTMENT_CODE
  WHERE d.IS_DEGREE_GRANTING = 'Y'
  GROUP BY d.DEPARTMENT_CODE, d.DEPARTMENT_NAME, s.SUBJECT_CODE, s.SUBJECT_CODE_DESC
)
SELECT m.COURSE_NUMBER, m.SUBJECT_TITLE, m.NUM_ENROLLED_STUDENTS,
       m.TERM_DESCRIPTION, m.ACADEMIC_YEAR, m.window_column,
       ss.DEPARTMENT_NAME, ss.SUBJECT_CODE, ss.SUBJECT_CODE_DESC,
       ss.avg_course_number_ascii, ss.var_course_number_ascii
FROM math_courses m
JOIN SIS_SUBJECT_CODE sc ON sc.COURSE_NUMBER = m.COURSE_NUMBER
JOIN subject_stats ss ON ss.DEPARTMENT_CODE = sc.DEPARTMENT_CODE
                     AND ss.SUBJECT_CODE = sc.SUBJECT_CODE
                     AND ss.SUBJECT_CODE_DESC = sc.SUBJECT_CODE_DESC