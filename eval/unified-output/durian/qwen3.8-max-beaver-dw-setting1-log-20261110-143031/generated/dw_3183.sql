SELECT T1.SPACE_UNIT,
       COUNT(T2.BUILDING_ROOM) AS NUM_ROOMS
FROM SPACE_UNIT AS T1
INNER JOIN ZPM_ROOMS_LOAD AS T2
        ON T1.SPACE_UNIT_CODE = T2.SPACE_UNIT_CODE
WHERE T2.ACCESS_LEVEL >= 1
GROUP BY T1.SPACE_UNIT
HAVING COUNT(T2.BUILDING_ROOM) > (
    SELECT AVG(cnt)
    FROM (
        SELECT COUNT(BUILDING_ROOM) AS cnt
        FROM ZPM_ROOMS_LOAD
        WHERE ACCESS_LEVEL >= 1
        GROUP BY SPACE_UNIT_CODE
    ) AS t
)