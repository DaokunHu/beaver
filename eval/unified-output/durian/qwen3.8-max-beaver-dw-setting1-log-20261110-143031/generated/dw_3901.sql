WITH inner_cte1 AS (
  SELECT t2.SUBJECT_TITLE, t0.COURSE_NUMBER, t2.DEPARTMENT_NAME,
         DENSE_RANK() OVER (PARTITION BY t1.OFFER_DEPT_CODE ORDER BY t1.OFFER_DEPT_CODE) AS window_column
  FROM SUBJECT_OFFERED_SUMMARY t0
  JOIN SUBJECT_OFFERED t1 ON t0.TERM_CODE = t1.TERM_CODE
  JOIN SUBJECT_SUMMARY t2 ON t1.TERM_CODE = t2.TERM_CODE
  WHERE t0.TERM_CODE = '2012SU' AND t2.TOTAL_UNITS > 0
),
dept_counts1 AS (
  SELECT DEPARTMENT_NAME, COUNT(*) AS total_subjects
  FROM SUBJECT_SUMMARY
  WHERE TERM_CODE = '2012SU' AND TOTAL_UNITS > 0
  GROUP BY DEPARTMENT_NAME
),
inner_cte2 AS (
  SELECT s.COURSE, s.COURSE_DESCRIPTION, s.DEPARTMENT_NAME, s.SCHOOL_NAME,
         c.PROGRAM_CODE, c.PROGRAM_TITLE, c.CATEGORY_CODE, c.CATEGORY_TITLE,
         c.FOUR_DIGIT_CODE, c.FOUR_DIGIT_TITLE,
         MIN(c.WAREHOUSE_LOAD_DATE) OVER (PARTITION BY c.CATEGORY_CODE ORDER BY c.CATEGORY_CODE) AS min_warehouse_load_date
  FROM SIS_COURSE_DESCRIPTION s
  JOIN CIP c ON c.PROGRAM_CODE = s.CIP_PROGRAM_CODE
  WHERE s.DEPARTMENT = 6
),
SchoolTotals2 AS (
  SELECT NULL AS COURSE, NULL AS COURSE_DESCRIPTION, NULL AS DEPARTMENT_NAME, SCHOOL_NAME,
         NULL AS PROGRAM_CODE, NULL AS PROGRAM_TITLE, NULL AS CATEGORY_CODE, NULL AS CATEGORY_TITLE,
         NULL AS FOUR_DIGIT_CODE, NULL AS FOUR_DIGIT_TITLE, NULL AS min_warehouse_load_date,
         COUNT(*) AS total_courses
  FROM inner_cte2
  GROUP BY SCHOOL_NAME
)
SELECT ic1.SUBJECT_TITLE, ic1.COURSE_NUMBER, ic1.DEPARTMENT_NAME, ic1.window_column,
       NULL AS total_subjects, ic2.COURSE, ic2.COURSE_DESCRIPTION, ic2.SCHOOL_NAME,
       ic2.PROGRAM_CODE, ic2.PROGRAM_TITLE, ic2.CATEGORY_CODE, ic2.CATEGORY_TITLE,
       ic2.FOUR_DIGIT_CODE, ic2.FOUR_DIGIT_TITLE, ic2.min_warehouse_load_date,
       NULL AS total_courses
FROM inner_cte1 ic1
LEFT JOIN SIS_COURSE_DESCRIPTION scd ON ic1.COURSE_NUMBER = scd.COURSE
LEFT JOIN inner_cte2 ic2 ON scd.COURSE = ic2.COURSE
UNION ALL
SELECT NULL, NULL, dc1.DEPARTMENT_NAME, NULL, dc1.total_subjects,
       s2.COURSE, s2.COURSE_DESCRIPTION, s2.SCHOOL_NAME, s2.PROGRAM_CODE, s2.PROGRAM_TITLE,
       s2.CATEGORY_CODE, s2.CATEGORY_TITLE, s2.FOUR_DIGIT_CODE, s2.FOUR_DIGIT_TITLE,
       s2.min_warehouse_load_date, s2.total_courses
FROM dept_counts1 dc1
LEFT JOIN SIS_COURSE_DESCRIPTION scd2 ON dc1.DEPARTMENT_NAME = scd2.DEPARTMENT_NAME
LEFT JOIN SchoolTotals2 s2 ON scd2.SCHOOL_NAME = s2.SCHOOL_NAME
ORDER BY DEPARTMENT_NAME, SCHOOL_NAME, CATEGORY_CODE, SUBJECT_TITLE, COURSE