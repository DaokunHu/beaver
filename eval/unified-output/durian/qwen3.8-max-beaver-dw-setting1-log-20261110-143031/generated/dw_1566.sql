SELECT
    t.BUILDING_NAME,
    t.FISCAL_PERIOD,
    t.total_room_area,
    SUM(t.ASSIGNABLE_AREA) OVER (
        PARTITION BY t.CAMPUS_SECTOR
        ORDER BY t.FISCAL_PERIOD, t.BUILDING_NAME
    ) AS running_sum_assignable_area,
    t.EXT_GROSS_AREA
FROM (
    SELECT
        b.BUILDING_NAME,
        b.CAMPUS_SECTOR,
        b.EXT_GROSS_AREA,
        h.FISCAL_PERIOD,
        h.ASSIGNABLE_AREA,
        SUM(r.AREA) AS total_room_area
    FROM FCLT_BUILDING b
    JOIN FCLT_BUILDING_HIST h
        ON b.FCLT_BUILDING_KEY = h.FCLT_BUILDING_KEY
    JOIN FCLT_ROOMS r
        ON h.FCLT_BUILDING_KEY = r.FCLT_BUILDING_KEY
    WHERE b.BUILDING_TYPE = 'ACADEMIC'
      AND b.OWNERSHIP_TYPE = 'OWNED'
      AND b.SITE = 'MIT'
      AND r.MAJOR_USE_DESC IN ('RESIDENT', 'LABS')
      AND b.FCLT_BUILDING_KEY <> '32'
    GROUP BY
        b.BUILDING_NAME,
        b.CAMPUS_SECTOR,
        b.EXT_GROSS_AREA,
        h.FISCAL_PERIOD,
        h.ASSIGNABLE_AREA
    HAVING SUM(r.AREA) > 1000
) t
ORDER BY t.FISCAL_PERIOD, t.BUILDING_NAME