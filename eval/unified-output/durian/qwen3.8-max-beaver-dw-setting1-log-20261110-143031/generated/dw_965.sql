SELECT
    tso.SUBJECT_ID,
    tso.SUBJECT_TITLE,
    tso.OFFER_DEPT_CODE,
    tso.OFFER_DEPT_NAME,
    tso.NUM_ENROLLED_STUDENTS,
    sd.DEPARTMENT_FULL_NAME,
    sd.SCHOOL_NAME,
    MIN(tso.NUM_ENROLLED_STUDENTS) OVER (PARTITION BY tso.OFFER_DEPT_CODE) AS min_num_enrolled_per_dept,
    v.DEPARTMENT_NAME,
    v.units_variance
FROM TIP_SUBJECT_OFFERED tso
JOIN STUDENT_DEPARTMENT sd
    ON tso.OFFER_DEPT_CODE = sd.DEPARTMENT_CODE
JOIN (
    SELECT
        sis.DEPARTMENT_CODE,
        sis.DEPARTMENT_NAME,
        VARIANCE(sos.TOTAL_UNITS) AS units_variance
    FROM SIS_DEPARTMENT sis
    JOIN COURSE_CATALOG_SUBJECT_OFFERED ccso
        ON sis.DEPARTMENT_CODE = ccso.DEPARTMENT_CODE
    JOIN SUBJECT_OFFERED_SUMMARY sos
        ON sis.DEPARTMENT_CODE = sos.OFFER_DEPT_CODE
    WHERE ccso.ACADEMIC_YEAR = 2022
      AND sis.IS_DEGREE_GRANTING = 'Y'
      AND sis.DEPARTMENT_CODE <> '7'
    GROUP BY sis.DEPARTMENT_CODE, sis.DEPARTMENT_NAME
) v
    ON tso.OFFER_DEPT_CODE = v.DEPARTMENT_CODE
WHERE tso.TERM_CODE = '2017JA'
  AND tso.OFFER_DEPT_NAME = 'Chemistry'
ORDER BY tso.OFFER_DEPT_CODE DESC, v.units_variance DESC