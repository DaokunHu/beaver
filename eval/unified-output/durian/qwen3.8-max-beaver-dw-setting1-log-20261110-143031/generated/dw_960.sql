SELECT T2.DEPARTMENT_NAME,
       COUNT(T1.SUBJECT_ID) AS num_subjects_offered,
       VARIANCE(T3.TOTAL_UNITS) AS variance_total_units
FROM COURSE_CATALOG_SUBJECT_OFFERED AS T1
INNER JOIN SIS_DEPARTMENT AS T2 ON T1.DEPARTMENT_CODE = T2.DEPARTMENT_CODE
INNER JOIN SUBJECT_OFFERED_SUMMARY AS T3 ON T2.DEPARTMENT_CODE = T3.OFFER_DEPT_CODE
WHERE T1.ACADEMIC_YEAR = 2022
  AND T2.IS_DEGREE_GRANTING = 'Y'
  AND T2.DEPARTMENT_CODE != '17'
  AND T2.DEPARTMENT_CODE != '7'
GROUP BY T2.DEPARTMENT_NAME
ORDER BY COUNT(T1.SUBJECT_ID) DESC
LIMIT 10