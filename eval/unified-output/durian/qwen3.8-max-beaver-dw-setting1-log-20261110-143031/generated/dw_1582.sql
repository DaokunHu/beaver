WITH inner_cte AS (
  SELECT t1.SUBJECT_CODE, t1.SUBJECT_TITLE, t1.DEPARTMENT_NAME, t0.SCHOOL_NAME
  FROM SIS_DEPARTMENT t0
  JOIN COURSE_CATALOG_SUBJECT_OFFERED t1 ON t0.DEPARTMENT_CODE = t1.DEPARTMENT_CODE
  WHERE t1.ACADEMIC_YEAR = 2024
    AND t1.TOTAL_UNITS = 12
    AND t1.DEPARTMENT_NAME = 'Mathematics'
),
school_counts AS (
  SELECT SCHOOL_NAME, COUNT(SUBJECT_CODE) AS subject_count
  FROM inner_cte
  GROUP BY SCHOOL_NAME
  HAVING COUNT(SUBJECT_CODE) >= 2
),
dept_unit_stats AS (
  SELECT d.DEPARTMENT_NAME,
         d.SCHOOL_NAME,
         VARIANCE(c.TOTAL_UNITS) AS total_units_variance,
         STDDEV(c.TOTAL_UNITS) AS total_units_stddev
  FROM SIS_COURSE_DESCRIPTION scd
  JOIN SIS_DEPARTMENT d ON scd.DEPARTMENT = d.DEPARTMENT_CODE
  JOIN CIS_COURSE_CATALOG c ON c.DEPARTMENT_CODE = d.DEPARTMENT_CODE
  WHERE c.TOTAL_UNITS IS NOT NULL
    AND d.IS_DEGREE_GRANTING = 'Y'
  GROUP BY d.DEPARTMENT_NAME, d.SCHOOL_NAME
)
SELECT ic.SUBJECT_CODE,
       ic.SUBJECT_TITLE,
       ic.DEPARTMENT_NAME,
       ic.SCHOOL_NAME,
       sc.subject_count,
       dus.total_units_variance,
       dus.total_units_stddev
FROM inner_cte ic
JOIN school_counts sc ON ic.SCHOOL_NAME = sc.SCHOOL_NAME
JOIN dept_unit_stats dus ON ic.DEPARTMENT_NAME = dus.DEPARTMENT_NAME
                        AND ic.SCHOOL_NAME = dus.SCHOOL_NAME
ORDER BY ic.SCHOOL_NAME, ic.SUBJECT_CODE