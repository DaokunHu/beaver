WITH engineering_dept_enrollment AS (
  WITH inner_cte AS (
    SELECT s.DEPARTMENT_NAME, SUM(t.NUM_ENROLLED_STUDENTS) AS total_enrollment
    FROM SIS_DEPARTMENT s
    JOIN TIP_SUBJECT_OFFERED t ON s.DEPARTMENT_CODE = t.OFFER_DEPT_CODE
    JOIN STUDENT_DEPARTMENT d ON t.OFFER_DEPT_CODE = d.DEPARTMENT_CODE
    WHERE s.SCHOOL_NAME = 'Engineering'
    GROUP BY s.DEPARTMENT_NAME
    HAVING SUM(t.NUM_ENROLLED_STUDENTS) > 50
  )
  SELECT i.DEPARTMENT_NAME, i.total_enrollment
  FROM inner_cte i
  JOIN (
    SELECT AVG(total_enrollment) AS avg_enrollment FROM (
      SELECT s.DEPARTMENT_NAME, SUM(t.NUM_ENROLLED_STUDENTS) AS total_enrollment
      FROM SIS_DEPARTMENT s
      JOIN TIP_SUBJECT_OFFERED t ON s.DEPARTMENT_CODE = t.OFFER_DEPT_CODE
      JOIN STUDENT_DEPARTMENT d ON t.OFFER_DEPT_CODE = d.DEPARTMENT_CODE
      WHERE s.SCHOOL_NAME = 'Engineering'
      GROUP BY s.DEPARTMENT_NAME
      HAVING SUM(t.NUM_ENROLLED_STUDENTS) > 50
    ) sub
  ) a ON i.total_enrollment > a.avg_enrollment
),
library_reserve_materials AS (
  WITH inner_cte AS (
    SELECT l.LIBRARY_COURSE_INSTRUCTOR_KEY, l.LIBRARY_RESERVE_CATALOG_KEY, l.TERM_CODE, l.SUBJECT_ID,
           t.TIP_MATERIAL_KEY, t.TIP_MATERIAL_STATUS_KEY, t.ISBN, s.SUBJECT_TITLE,
           MIN(t.TIP_MATERIAL_STATUS_KEY) OVER (ORDER BY s.NUM_ENROLLED_STUDENTS ROWS BETWEEN 3 PRECEDING AND 1 FOLLOWING) AS window_column,
           s.TIP_SUBJECT_OFFERED_KEY
    FROM LIBRARY_RESERVE_MATRL_DETAIL l
    JOIN TIP_DETAIL t ON l.SUBJECT_ID = t.SUBJECT_ID
    JOIN TIP_SUBJECT_OFFERED s ON t.SUBJECT_ID = s.SUBJECT_ID
    WHERE l.LIBRARY_MATERIAL_STATUS_KEY = 'U'
  )
  SELECT inner_cte.LIBRARY_COURSE_INSTRUCTOR_KEY, inner_cte.LIBRARY_RESERVE_CATALOG_KEY, inner_cte.TERM_CODE,
         inner_cte.SUBJECT_ID, inner_cte.TIP_MATERIAL_KEY, inner_cte.TIP_MATERIAL_STATUS_KEY, inner_cte.ISBN,
         inner_cte.SUBJECT_TITLE, inner_cte.window_column, s.RESPONSIBLE_FACULTY_NAME, s.OFFER_DEPT_NAME, s.OFFER_DEPT_CODE
  FROM inner_cte
  JOIN TIP_SUBJECT_OFFERED s ON inner_cte.TIP_SUBJECT_OFFERED_KEY = s.TIP_SUBJECT_OFFERED_KEY
)
SELECT ede.DEPARTMENT_NAME, ede.total_enrollment, lrm.LIBRARY_COURSE_INSTRUCTOR_KEY, lrm.LIBRARY_RESERVE_CATALOG_KEY,
       lrm.TERM_CODE, lrm.SUBJECT_ID, lrm.TIP_MATERIAL_KEY, lrm.TIP_MATERIAL_STATUS_KEY, lrm.ISBN, lrm.SUBJECT_TITLE,
       lrm.window_column, lrm.RESPONSIBLE_FACULTY_NAME, lrm.OFFER_DEPT_NAME
FROM engineering_dept_enrollment ede
JOIN library_reserve_materials lrm ON ede.DEPARTMENT_NAME = lrm.OFFER_DEPT_NAME