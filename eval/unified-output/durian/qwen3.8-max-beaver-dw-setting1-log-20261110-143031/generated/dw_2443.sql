SELECT
  at.ACADEMIC_YEAR,
  at.ACADEMIC_YEAR_DESC,
  AVG(CASE WHEN ccso.DEPARTMENT_NAME = 'Mathematics' THEN ccso.TOTAL_UNITS END) AS math_avg_total_units,
  AVG(CASE WHEN ccso.DEPARTMENT_NAME = 'Mathematics' THEN ccso.TOTAL_UNITS END) - AVG(ccso.TOTAL_UNITS) AS difference_from_all_subjects_avg
FROM ACADEMIC_TERMS_ALL ata
JOIN ACADEMIC_TERMS at ON ata.TERM_CODE = at.TERM_CODE
JOIN COURSE_CATALOG_SUBJECT_OFFERED ccso ON at.TERM_CODE = ccso.EFFECTIVE_TERM_CODE
WHERE at.IS_REGULAR_TERM = 'Y'
GROUP BY at.ACADEMIC_YEAR, at.ACADEMIC_YEAR_DESC
ORDER BY at.ACADEMIC_YEAR