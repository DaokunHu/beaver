SELECT
    sd.DEPARTMENT_NAME,
    MAX(tso.NUM_ENROLLED_STUDENTS) - MIN(tso.NUM_ENROLLED_STUDENTS) AS range_enrolled_students,
    VARIANCE(tso.NUM_ENROLLED_STUDENTS) AS variance_enrolled_students,
    COUNT(DISTINCT tso.SUBJECT_ID) AS distinct_subject_count,
    MIN(td.ISBN) AS min_isbn,
    AVG(tso.NUM_ENROLLED_STUDENTS) AS avg_enrolled_students
FROM TIP_SUBJECT_OFFERED tso
JOIN SIS_DEPARTMENT sd
    ON tso.OFFER_DEPT_CODE = sd.DEPARTMENT_CODE
JOIN SIS_COURSE_DESCRIPTION scd
    ON sd.DEPARTMENT_CODE = scd.DEPARTMENT
JOIN TIP_DETAIL td
    ON td.SUBJECT_ID = tso.SUBJECT_ID
WHERE sd.IS_DEGREE_GRANTING = 'Y'
  AND scd.COURSE_LEVEL = 'G'
  AND tso.NUM_ENROLLED_STUDENTS > 2
GROUP BY sd.DEPARTMENT_NAME