SELECT
    T1.MAJOR_USE_DESC,
    T2.ORGANIZATION_NAME,
    COUNT(T1.FCLT_ROOM_KEY) AS NUM_OF_ROOMS,
    MIN(T1.FLOOR) AS MIN_FLOOR,
    EXP(AVG(LN(T4.NUM_OF_SUPERVISEES))) AS GEO_MEAN_SUPERVISEES,
    SUM(T4.RESEARCH_VOLUME) AS TOTAL_RESEARCH_VOLUME
FROM FCLT_ROOMS T1
INNER JOIN FCLT_ORGANIZATION T2
    ON T1.FCLT_ORGANIZATION_KEY = T2.FCLT_ORGANIZATION_KEY
INNER JOIN SPACE_UNIT T3
    ON T2.DLC_KEY = T3.DLC_KEY
INNER JOIN SPACE_SUPERVISOR_USAGE T4
    ON T4.DEPT_NAMES = T3.DLC_KEY
WHERE T1.AREA > 100
  AND T1.ACCESS_LEVEL = 1
  AND T4.NUM_OF_SUPERVISEES > 0
  AND T4.RESEARCH_VOLUME > 0
GROUP BY T1.MAJOR_USE_DESC, T2.ORGANIZATION_NAME