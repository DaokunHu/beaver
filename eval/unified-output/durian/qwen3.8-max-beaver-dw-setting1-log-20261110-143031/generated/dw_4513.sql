WITH SubjectOfferings AS (
    SELECT
        t0.TIP_SUBJECT_OFFERED_KEY,
        t0.SUBJECT_TITLE,
        t0.OFFER_DEPT_NAME,
        t1.TERM_DESCRIPTION,
        RANK() OVER (PARTITION BY t0.OFFER_DEPT_NAME ORDER BY t0.TIP_SUBJECT_OFFERED_KEY) AS subject_rank_in_dept,
        t0.SUBJECT_ID,
        t1.TERM_START_DATE,
        t1.TERM_END_DATE
    FROM TIP_SUBJECT_OFFERED t0
    JOIN ACADEMIC_TERMS t1 ON t0.TERM_CODE = t1.TERM_CODE
    JOIN ACADEMIC_TERM_PARAMETER t2 ON t1.TERM_CODE = t2.TERM_CODE
    WHERE t1.TERM_DESCRIPTION = 'Fall Term 2024-2025'
),
LibrarySubjectStats AS (
    SELECT
        t1.COURSE_NUMBER,
        t1.COURSE_NUMBER_DESC,
        t1.NUM_ENROLLED_STUDENTS,
        t2.LIBRARY_RESERVE_CATALOG_KEY,
        DENSE_RANK() OVER (PARTITION BY t2.LIBRARY_MATERIAL_STATUS_KEY ORDER BY t2.LIBRARY_MATERIAL_STATUS_KEY) AS dense_rank_material_status,
        t1.SUBJECT_ID
    FROM LIBRARY_SUBJECT_OFFERED t1
    JOIN LIBRARY_RESERVE_MATRL_DETAIL t2 ON t1.SUBJECT_ID = t2.SUBJECT_ID
    WHERE t1.NUM_ENROLLED_STUDENTS > 0
      AND t2.LIBRARY_MATERIAL_STATUS_KEY = 'U'
)
SELECT
    so.TIP_SUBJECT_OFFERED_KEY,
    so.SUBJECT_TITLE,
    so.OFFER_DEPT_NAME,
    so.TERM_DESCRIPTION,
    so.subject_rank_in_dept,
    lss.COURSE_NUMBER,
    lss.COURSE_NUMBER_DESC,
    lss.NUM_ENROLLED_STUDENTS,
    lss.LIBRARY_RESERVE_CATALOG_KEY,
    lss.dense_rank_material_status,
    so.TERM_START_DATE,
    so.TERM_END_DATE
FROM SubjectOfferings so
JOIN LibrarySubjectStats lss ON so.SUBJECT_ID = lss.SUBJECT_ID
ORDER BY so.TIP_SUBJECT_OFFERED_KEY, lss.COURSE_NUMBER