WITH building_cv AS (
  SELECT b.FCLT_BUILDING_KEY,
         b.BUILDING_NAME_LONG,
         STDDEV(r.AREA) / AVG(r.AREA) AS cv_area
  FROM FCLT_BUILDING b
  JOIN FCLT_ROOMS r ON r.FCLT_BUILDING_KEY = b.FCLT_BUILDING_KEY
  WHERE b.BUILDING_TYPE = 'ACADEMIC'
    AND b.BUILDING_NAME <> 'ASHDOWN HOUSE'
  GROUP BY b.FCLT_BUILDING_KEY, b.BUILDING_NAME_LONG
)
SELECT bc.cv_area,
       bc.BUILDING_NAME_LONG,
       a.POSTAL_CODE
FROM building_cv bc
JOIN FCLT_BUILDING_ADDRESS a ON a.FCLT_BUILDING_KEY = bc.FCLT_BUILDING_KEY
WHERE bc.cv_area > (SELECT AVG(cv_area) FROM building_cv)