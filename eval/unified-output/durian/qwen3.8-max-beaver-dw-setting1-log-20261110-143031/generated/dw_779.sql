SELECT
    t.ACADEMIC_YEAR,
    t.ACADEMIC_YEAR_DESC,
    AVG(c.TOTAL_UNITS) AS avg_total_units,
    STDDEV(c.TOTAL_UNITS) AS stddev_total_units,
    VARIANCE(CASE WHEN t.TERM_STATUS = 'Previous' THEN c.TOTAL_UNITS END) AS var_total_units
FROM ACADEMIC_TERMS t
JOIN ACADEMIC_TERMS_ALL ta
    ON t.TERM_CODE = ta.TERM_CODE
JOIN COURSE_CATALOG_SUBJECT_OFFERED c
    ON t.TERM_CODE = c.EFFECTIVE_TERM_CODE
WHERE t.IS_REGULAR_TERM = 'Y'
  AND c.DEPARTMENT_NAME = 'Mathematics'
GROUP BY t.ACADEMIC_YEAR, t.ACADEMIC_YEAR_DESC
ORDER BY t.ACADEMIC_YEAR