SELECT
  t0.SUBJECT_TITLE,
  t1.DEPARTMENT_NAME,
  DENSE_RANK() OVER (ORDER BY t2.SUBJECT_CODE ROWS BETWEEN 2 PRECEDING AND CURRENT ROW) AS window_column,
  t3.num_offered_subjects,
  t3.min_enrolled_students
FROM SUBJECT_OFFERED_SUMMARY t0
JOIN SIS_COURSE_DESCRIPTION t1 ON t0.COURSE_NUMBER = t1.COURSE
JOIN COURSE_CATALOG_SUBJECT_OFFERED t2 ON t1.COURSE = t2.SUBJECT_CODE
JOIN (
  SELECT
    s.DEPARTMENT_NAME,
    s.SCHOOL_NAME,
    COUNT(l.LIBRARY_SUBJECT_OFFERED_KEY) AS num_offered_subjects,
    MIN(l.NUM_ENROLLED_STUDENTS) AS min_enrolled_students
  FROM LIBRARY_SUBJECT_OFFERED l
  JOIN SIS_SUBJECT_CODE s ON l.COURSE_NUMBER = s.COURSE_NUMBER
  WHERE l.NUM_ENROLLED_STUDENTS > 3
  GROUP BY s.DEPARTMENT_NAME, s.SCHOOL_NAME
) t3 ON t1.DEPARTMENT_NAME = t3.DEPARTMENT_NAME AND t1.SCHOOL_NAME = t3.SCHOOL_NAME
WHERE t2.TERM_CODE = '2022FA' AND t0.TOTAL_UNITS = 12