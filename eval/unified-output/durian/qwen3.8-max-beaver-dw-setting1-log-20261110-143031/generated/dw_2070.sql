SELECT
    t1.SUBJECT_CODE,
    t1.SUBJECT_CODE_DESC,
    t0.DEPARTMENT_NAME,
    t1.SCHOOL_NAME,
    AVG(t0.DEPT_BUDGET_CODE) OVER (PARTITION BY t1.SCHOOL_NAME ORDER BY t0.DEPARTMENT_NAME) AS avg_dept_budget_code,
    t2.SUBJECT_TITLE,
    t2.TOTAL_UNITS,
    DENSE_RANK() OVER (PARTITION BY t0.DEPARTMENT_CODE ORDER BY t0.DEPARTMENT_CODE) AS dense_rank_dept_code,
    COUNT(t2.SUBJECT_OFFERED_SUMMARY_KEY) OVER (PARTITION BY t0.DEPARTMENT_CODE) AS num_subjects_offered
FROM SIS_DEPARTMENT t0
JOIN SIS_SUBJECT_CODE t1
    ON t0.SCHOOL_CODE = t1.SCHOOL_CODE
   AND t0.DEPARTMENT_CODE = t1.DEPARTMENT_CODE
JOIN SUBJECT_OFFERED_SUMMARY t2
    ON t0.DEPARTMENT_CODE = t2.OFFER_DEPT_CODE
WHERE t0.IS_DEGREE_GRANTING = 'Y'
  AND t0.DEPARTMENT_NAME = 'Mathematics'
ORDER BY t0.DEPARTMENT_NAME, dense_rank_dept_code