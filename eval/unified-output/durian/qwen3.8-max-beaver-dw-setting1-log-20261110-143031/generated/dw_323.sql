SELECT
    T1.DEPARTMENT_NAME,
    COUNT(DISTINCT T3.SUBJECT_ID) AS num_degree_granting_subjects
FROM SIS_COURSE_DESCRIPTION T1
INNER JOIN SIS_SUBJECT_CODE T2
    ON T1.COURSE = T2.COURSE_NUMBER
INNER JOIN LIBRARY_SUBJECT_OFFERED T3
    ON T2.COURSE_NUMBER = T3.COURSE_NUMBER
WHERE T1.IS_DEGREE_GRANTING = 'Y'
  AND T3.TERM_CODE = '2014FA'
  AND T3.NUM_ENROLLED_STUDENTS > 5
GROUP BY T1.DEPARTMENT_NAME