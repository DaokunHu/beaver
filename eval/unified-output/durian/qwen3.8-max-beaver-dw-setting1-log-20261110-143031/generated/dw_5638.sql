SELECT
    ata.ACADEMIC_YEAR,
    ata.ACADEMIC_YEAR_DESC,
    AVG(ccso.TOTAL_UNITS) AS avg_total_units,
    STDDEV(ccso.TOTAL_UNITS) AS stddev_total_units
FROM COURSE_CATALOG_SUBJECT_OFFERED ccso
JOIN ACADEMIC_TERMS_ALL ata ON ccso.TERM_CODE = ata.TERM_CODE
JOIN TIP_DETAIL td ON ata.TERM_CODE = td.TERM_CODE AND ccso.SUBJECT_ID = td.SUBJECT_ID
WHERE ccso.DEPARTMENT_NAME = 'Mathematics'
  AND td.TIP_MATERIAL_STATUS_KEY IN ('RQ', 'EO')
GROUP BY ata.ACADEMIC_YEAR, ata.ACADEMIC_YEAR_DESC
ORDER BY ata.ACADEMIC_YEAR