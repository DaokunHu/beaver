SELECT
    m.DLC_NAME AS department_name,
    f.FCLT_ORGANIZATION_KEY AS organization_key,
    COUNT(f.FCLT_ORGANIZATION_KEY) AS num_organizations,
    MIN(m.MASTER_DEPT_HIER_LEVEL_3_CODE) AS min_level3_code,
    MAX(m.MASTER_DEPT_HIER_LEVEL_3_CODE) AS max_level3_code,
    o.ORGANIZATION_NAME AS organization_name,
    COUNT(su.SPACE_UNIT_KEY) AS num_space_units,
    AVG(su.SPACE_UNIT_KEY) AS avg_space_units,
    CASE
        WHEN COUNT(su.SPACE_UNIT_KEY) > AVG(su.SPACE_UNIT_KEY) THEN 'LARGE_HOLDER'
        WHEN COUNT(su.SPACE_UNIT_KEY) < AVG(su.SPACE_UNIT_KEY) THEN 'SMALL_HOLDER'
        ELSE 'AVERAGE_HOLDER'
    END AS holder_category
FROM MASTER_DEPT_HIERARCHY m
JOIN FCLT_ORG_DLC_KEY f ON m.DLC_KEY = f.DLC_KEY
JOIN FCLT_ORGANIZATION o ON f.DLC_KEY = o.DLC_KEY
JOIN SPACE_UNIT su ON o.DLC_KEY = su.DLC_KEY
WHERE m.MASTER_DEPT_HIER_LEVEL_2_NAME = 'Provost Area'
GROUP BY m.DLC_NAME, f.FCLT_ORGANIZATION_KEY, o.ORGANIZATION_NAME
ORDER BY m.DLC_NAME, o.ORGANIZATION_NAME