SELECT
    td.SUBJECT_ID,
    ata.TERM_DESCRIPTION,
    td.TIP_MATERIAL_STATUS_KEY,
    at.ACADEMIC_YEAR,
    sd.DEPARTMENT_NAME,
    RANK() OVER (PARTITION BY at.ACADEMIC_YEAR ORDER BY td.SUBJECT_ID) AS subject_rank
FROM TIP_DETAIL td
JOIN ACADEMIC_TERMS at
    ON td.TERM_CODE = at.TERM_CODE
JOIN ACADEMIC_TERMS_ALL ata
    ON at.TERM_CODE = ata.TERM_CODE
JOIN TIP_SUBJECT_OFFERED tso
    ON td.TIP_SUBJECT_OFFERED_KEY = tso.TIP_SUBJECT_OFFERED_KEY
JOIN SIS_DEPARTMENT sd
    ON tso.OFFER_DEPT_CODE = sd.DEPARTMENT_CODE
WHERE td.TERM_CODE = '2010FA'