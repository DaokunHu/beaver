WITH dept_cv AS (
    SELECT STDDEV(tso.NUM_ENROLLED_STUDENTS) / AVG(tso.NUM_ENROLLED_STUDENTS) AS coefficient_of_variation
    FROM TIP_SUBJECT_OFFERED tso
    JOIN STUDENT_DEPARTMENT sd ON tso.OFFER_DEPT_CODE = sd.DEPARTMENT_CODE
    WHERE sd.DEPARTMENT_NAME = 'Mathematics'
)
SELECT
    sc.SUBJECT_CODE,
    sc.SUBJECT_CODE_DESC,
    sc.DEPARTMENT_NAME,
    sc.SCHOOL_NAME,
    l.SUBJECT_TITLE,
    l.NUM_ENROLLED_STUDENTS,
    ROW_NUMBER() OVER (PARTITION BY sc.DEPARTMENT_NAME ORDER BY sc.SUBJECT_CODE) AS row_number,
    cv.coefficient_of_variation
FROM LIBRARY_SUBJECT_OFFERED l
JOIN SIS_SUBJECT_CODE sc ON l.COURSE_NUMBER = sc.COURSE_NUMBER
JOIN SIS_DEPARTMENT d ON sc.DEPARTMENT_CODE = d.DEPARTMENT_CODE
CROSS JOIN dept_cv cv
WHERE l.TERM_CODE = '2014FA'
  AND l.NUM_ENROLLED_STUDENTS > 5
  AND d.DEPARTMENT_NAME = 'Mathematics'
  AND d.DEPARTMENT_CODE = '18'
ORDER BY sc.SUBJECT_CODE