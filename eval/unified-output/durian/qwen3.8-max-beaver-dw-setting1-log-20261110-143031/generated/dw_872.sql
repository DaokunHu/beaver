SELECT
  t0.SUBJECT_ID,
  t0.SUBJECT_CODE,
  t0.SUBJECT_NUMBER,
  t0.DEPARTMENT_NAME,
  t0.SUBJECT_SHORT_TITLE,
  t0.SUBJECT_TITLE,
  t0.LECTURE_UNITS,
  t0.LAB_UNITS,
  t0.TOTAL_UNITS,
  t0.GRADE_TYPE,
  t0.GRADE_RULE,
  MIN(t0.TOTAL_UNITS) OVER (PARTITION BY t0.DEPARTMENT_CODE ORDER BY t0.DEPARTMENT_CODE) AS min_total_units_by_dept,
  gm.geometric_mean_total_units
FROM COURSE_CATALOG_SUBJECT_OFFERED t0
JOIN CIS_COURSE_CATALOG t1
  ON t0.SUBJECT_ID = t1.SUBJECT_ID
JOIN (
  SELECT
    t3.DEPARTMENT_NAME,
    EXP(AVG(LN(t2.TOTAL_UNITS))) AS geometric_mean_total_units
  FROM COURSE_CATALOG_SUBJECT_OFFERED t2
  JOIN SIS_COURSE_DESCRIPTION t3
    ON t2.SUBJECT_CODE = t3.COURSE
  WHERE t2.IS_OFFERED_THIS_YEAR = 'Y'
    AND t2.TOTAL_UNITS > 0
    AND t3.DEPARTMENT_NAME = 'Mathematics'
  GROUP BY t3.DEPARTMENT_NAME
) gm
  ON t0.DEPARTMENT_NAME = gm.DEPARTMENT_NAME
WHERE t0.ACADEMIC_YEAR = 2024
  AND t0.DEPARTMENT_NAME = 'Mathematics'
ORDER BY t0.DEPARTMENT_NAME, t0.SUBJECT_CODE