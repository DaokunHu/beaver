SELECT
    so.SUBJECT_KEY,
    so.SUBJECT_TITLE,
    ss.DEPARTMENT_NAME,
    COUNT(so.SUBJECT_KEY) AS num_subject_offerings,
    SUM(sos.TOTAL_UNITS) AS total_units,
    SUM(so.NUM_ENROLLED_STUDENTS) AS total_num_enrolled_students
FROM SUBJECT_OFFERED so
JOIN SUBJECT_OFFERED_SUMMARY sos ON so.SUBJECT_ID = sos.SUBJECT_ID
JOIN SUBJECT_SUMMARY ss ON so.SUBJECT_ID = ss.SUBJECT_ID
WHERE so.TERM_CODE = '2012SU'
  AND ss.DEPARTMENT_NAME = 'Harvard Cross-Enrollment Prog'
GROUP BY so.SUBJECT_KEY, so.SUBJECT_TITLE, ss.DEPARTMENT_NAME