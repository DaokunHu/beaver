SELECT
    b.BUILDING_NAME,
    h.FISCAL_PERIOD,
    SUM(r.AREA) AS total_room_area,
    SUM(h.ASSIGNABLE_AREA) OVER (PARTITION BY b.CAMPUS_SECTOR ORDER BY h.FISCAL_PERIOD, b.BUILDING_NAME) AS running_sum_assignable_area,
    b.EXT_GROSS_AREA
FROM FCLT_BUILDING b
JOIN FCLT_BUILDING_HIST h ON b.FCLT_BUILDING_KEY = h.FCLT_BUILDING_KEY
JOIN FCLT_ROOMS r ON h.FCLT_BUILDING_KEY = r.FCLT_BUILDING_KEY
WHERE b.BUILDING_TYPE = 'ACADEMIC'
  AND b.OWNERSHIP_TYPE = 'OWNED'
  AND b.SITE = 'MIT'
  AND b.FCLT_BUILDING_KEY <> 32
  AND r.MAJOR_USE_DESC IN ('RESIDENT', 'LABS')
GROUP BY b.BUILDING_NAME, h.FISCAL_PERIOD, h.ASSIGNABLE_AREA, b.CAMPUS_SECTOR, b.EXT_GROSS_AREA
HAVING SUM(r.AREA) > 1000
ORDER BY h.FISCAL_PERIOD, b.BUILDING_NAME