SELECT
    T1.FULL_NAME,
    T1.EMAIL_ADDRESS,
    T1.DEPARTMENT_FULL_NAME,
    T1.NAME_LENGTH_DIFF,
    T2.OFFER_SCHOOL_NAME,
    T2.MIN_ENROLLED_STUDENTS,
    T2.TOTAL_UNITS
FROM (
    SELECT
        S.FULL_NAME,
        S.EMAIL_ADDRESS,
        S.DEPARTMENT,
        D.DEPARTMENT_FULL_NAME,
        LENGTH(S.FULL_NAME) - AVG(LENGTH(S.FULL_NAME)) OVER () AS NAME_LENGTH_DIFF
    FROM MIT_STUDENT_DIRECTORY S
    INNER JOIN SIS_DEPARTMENT D
        ON S.DEPARTMENT = D.DEPARTMENT_CODE
    WHERE D.IS_DEGREE_GRANTING = 'Y'
      AND S.STUDENT_YEAR = 'G'
) T1
INNER JOIN (
    SELECT
        L.OFFER_DEPT_CODE,
        L.OFFER_SCHOOL_NAME,
        MIN(L.NUM_ENROLLED_STUDENTS) AS MIN_ENROLLED_STUDENTS,
        SUM(SO.TOTAL_UNITS) AS TOTAL_UNITS
    FROM LIBRARY_SUBJECT_OFFERED L
    INNER JOIN TIP_DETAIL TD
        ON L.SUBJECT_ID = TD.SUBJECT_ID
    INNER JOIN SUBJECT_OFFERED_SUMMARY SO
        ON SO.SUBJECT_ID = TD.SUBJECT_ID
    WHERE TD.TIP_MATERIAL_STATUS_KEY = 'RQ'
    GROUP BY L.OFFER_DEPT_CODE, L.OFFER_SCHOOL_NAME
) T2
    ON T1.DEPARTMENT = T2.OFFER_DEPT_CODE