SELECT
    d.DEPARTMENT_NAME,
    t.SUBJECT_TITLE,
    t.NUM_ENROLLED_STUDENTS,
    sd.SCHOOL_NAME,
    DENSE_RANK() OVER (ORDER BY d.DEPARTMENT_CODE) AS dense_rank
FROM TIP_SUBJECT_OFFERED t
JOIN SIS_DEPARTMENT d
    ON d.DEPARTMENT_CODE = t.OFFER_DEPT_CODE
JOIN STUDENT_DEPARTMENT sd
    ON sd.DEPARTMENT_CODE = t.OFFER_DEPT_CODE
WHERE t.OFFER_DEPT_CODE = '18'
  AND t.NUM_ENROLLED_STUDENTS > 0
  AND d.IS_DEGREE_GRANTING = 'Y'
  AND t.NUM_ENROLLED_STUDENTS > (
        SELECT AVG(t2.NUM_ENROLLED_STUDENTS)
        FROM TIP_SUBJECT_OFFERED t2
        WHERE t2.OFFER_DEPT_CODE = '18'
      )
ORDER BY d.DEPARTMENT_CODE, t.SUBJECT_TITLE