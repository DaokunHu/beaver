WITH Subq1 AS (
    SELECT
        t.SUBJECT_ID,
        t.SUBJECT_TITLE,
        t.NUM_ENROLLED_STUDENTS,
        d.DEPARTMENT_NAME,
        d.DEPARTMENT_FULL_NAME,
        ROW_NUMBER() OVER (PARTITION BY d.DEPARTMENT_NAME ORDER BY t.SUBJECT_ID) AS window_column
    FROM TIP_SUBJECT_OFFERED t
    JOIN SIS_DEPARTMENT d
        ON d.DEPARTMENT_CODE = t.OFFER_DEPT_CODE
    WHERE t.TERM_CODE = '2019FA'
),
Subq2 AS (
    SELECT
        s.SUBJECT_TITLE,
        s.DEPARTMENT_NAME,
        s.TOTAL_UNITS,
        ROW_NUMBER() OVER (ORDER BY s.SUBJECT_TITLE ROWS BETWEEN 2 PRECEDING AND 1 FOLLOWING) AS window_column
    FROM SUBJECT_SUMMARY s
    JOIN ACADEMIC_TERMS a
        ON a.TERM_CODE = s.TERM_CODE
    WHERE s.TERM_CODE = '2009SP'
)
SELECT
    s1.SUBJECT_ID,
    s1.SUBJECT_TITLE,
    s1.NUM_ENROLLED_STUDENTS,
    s1.DEPARTMENT_NAME,
    s1.DEPARTMENT_FULL_NAME,
    s1.window_column,
    s2.TOTAL_UNITS,
    s2.window_column
FROM Subq1 s1
JOIN Subq2 s2
    ON s1.SUBJECT_TITLE = s2.SUBJECT_TITLE
   AND s1.DEPARTMENT_NAME = s2.DEPARTMENT_NAME