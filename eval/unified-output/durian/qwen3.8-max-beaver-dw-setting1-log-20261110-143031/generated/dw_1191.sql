SELECT
    t0.SUBJECT_ID,
    t0.SUBJECT_CODE,
    t0.SUBJECT_NUMBER,
    t0.DEPARTMENT_NAME,
    t0.SUBJECT_SHORT_TITLE,
    t0.SUBJECT_TITLE,
    t0.LECTURE_UNITS,
    t0.LAB_UNITS,
    t0.TOTAL_UNITS,
    t0.GRADE_TYPE,
    t0.GRADE_RULE,
    MIN(t0.TOTAL_UNITS) OVER (PARTITION BY t0.DEPARTMENT_CODE) AS min_total_units_by_dept,
    dsc.subject_code_count,
    dsc.min_dept_budget_code
FROM COURSE_CATALOG_SUBJECT_OFFERED t0
JOIN CIS_COURSE_CATALOG t1
    ON t0.SUBJECT_ID = t1.SUBJECT_ID
JOIN (
    SELECT
        s.SUBJECT_CODE,
        COUNT(s.SUBJECT_CODE) AS subject_code_count,
        MIN(d.DEPT_BUDGET_CODE) AS min_dept_budget_code
    FROM SIS_DEPARTMENT d
    JOIN SIS_SUBJECT_CODE s
        ON d.DEPARTMENT_CODE = s.DEPARTMENT_CODE
    WHERE d.IS_DEGREE_GRANTING = 'Y'
      AND d.DEPARTMENT_NAME = 'Mathematics'
    GROUP BY d.DEPARTMENT_NAME, s.SUBJECT_CODE
) dsc
    ON t0.SUBJECT_CODE = dsc.SUBJECT_CODE
WHERE t0.ACADEMIC_YEAR = 2024
  AND t0.DEPARTMENT_NAME = 'Mathematics'
ORDER BY t0.DEPARTMENT_CODE, t0.SUBJECT_CODE, t0.SUBJECT_NUMBER