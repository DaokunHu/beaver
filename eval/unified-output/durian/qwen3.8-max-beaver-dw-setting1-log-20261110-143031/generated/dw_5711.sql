SELECT
    T2.DEPARTMENT_NAME,
    T2.SCHOOL_NAME,
    COUNT(DISTINCT T1.COURSE) AS num_unique_courses,
    MIN(T1.CIP_PROGRAM_CODE) AS min_cip_program_code
FROM SIS_COURSE_DESCRIPTION T1
INNER JOIN SIS_DEPARTMENT T2
    ON T1.DEPARTMENT = T2.DEPARTMENT_CODE
WHERE T2.IS_DEGREE_GRANTING = 'Y'
  AND T2.DEPARTMENT_NAME = 'Mathematics'
GROUP BY T2.DEPARTMENT_NAME, T2.SCHOOL_NAME