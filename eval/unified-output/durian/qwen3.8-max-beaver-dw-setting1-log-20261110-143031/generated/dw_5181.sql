SELECT
    d.DEPARTMENT_FULL_NAME,
    MAX(c.TOTAL_UNITS) - MIN(c.TOTAL_UNITS) AS total_units_range,
    VARIANCE(c.TOTAL_UNITS) AS total_units_variance
FROM SIS_COURSE_DESCRIPTION scd
JOIN SIS_DEPARTMENT d
    ON scd.DEPARTMENT = d.DEPARTMENT_CODE
JOIN COURSE_CATALOG_SUBJECT_OFFERED c
    ON d.DEPARTMENT_CODE = c.DEPARTMENT_CODE
WHERE c.ACADEMIC_YEAR = 2024
  AND d.IS_DEGREE_GRANTING = 'Y'
  AND d.DEPARTMENT_CODE <> '7'
GROUP BY d.DEPARTMENT_FULL_NAME