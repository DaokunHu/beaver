SELECT
    d.DEPARTMENT_NAME,
    SUM(a.CLEARING_COST_COLLECTOR) AS total_clearing_cost_collector
FROM SIS_DEPARTMENT d
JOIN SIS_ADMIN_DEPARTMENT a
    ON a.SIS_ADMIN_DEPARTMENT_CODE = d.DEPARTMENT_CODE
WHERE d.IS_DEGREE_GRANTING = 'Y'
  AND d.DEPT_BUDGET_CODE > 100000
  AND d.DEPARTMENT_NAME != 'Mathematics'
  AND d.DEPARTMENT_CODE != '8'
GROUP BY d.DEPARTMENT_NAME
HAVING SUM(a.CLEARING_COST_COLLECTOR) > (
    SELECT AVG(a2.CLEARING_COST_COLLECTOR)
    FROM SIS_DEPARTMENT d2
    JOIN SIS_ADMIN_DEPARTMENT a2
        ON a2.SIS_ADMIN_DEPARTMENT_CODE = d2.DEPARTMENT_CODE
    WHERE d2.IS_DEGREE_GRANTING = 'Y'
      AND d2.DEPT_BUDGET_CODE > 100000
      AND d2.DEPARTMENT_NAME != 'Mathematics'
      AND d2.DEPARTMENT_CODE != '8'
)