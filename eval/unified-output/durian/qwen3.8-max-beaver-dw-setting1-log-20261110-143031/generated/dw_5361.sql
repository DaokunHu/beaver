SELECT
    T1.MASTER_DEPT_HIER_LEVEL_2_NAME,
    T2.ORGANIZATION_NAME,
    COUNT(T2.FCLT_ORGANIZATION_KEY) AS number_of_organizations,
    MIN(T2.ORGANIZATION_NUMBER) AS minimum_organization_number
FROM MASTER_DEPT_HIERARCHY T1
JOIN FCLT_ORGANIZATION T2
    ON T1.DLC_KEY = T2.DLC_KEY
WHERE T2.ASSIGNABLE = 1
  AND T2.ORGANIZATION_NAME <> 'ADMISSIONS'
  AND T2.ORGANIZATION_ID NOT IN ('138', '250')
GROUP BY T1.MASTER_DEPT_HIER_LEVEL_2_NAME, T2.ORGANIZATION_NAME