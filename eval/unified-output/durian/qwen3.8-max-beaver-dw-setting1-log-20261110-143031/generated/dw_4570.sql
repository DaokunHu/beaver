WITH subq1 AS (
  SELECT t1.DEPARTMENT_NAME,
         MAX(t0.TOTAL_UNITS) AS max_total_units,
         t1.SCHOOL_NAME
  FROM CIS_COURSE_CATALOG t0
  JOIN SIS_SUBJECT_CODE t1 ON t0.DEPARTMENT_CODE = t1.DEPARTMENT_CODE
  GROUP BY t1.DEPARTMENT_NAME, t1.SCHOOL_NAME
  HAVING MAX(t0.TOTAL_UNITS) > 6
),
subq2 AS (
  SELECT t2.FULL_NAME,
         t2.EMAIL_ADDRESS,
         t1.DEPARTMENT_NAME,
         t0.COURSE_DESCRIPTION,
         t0.COURSE_LEVEL,
         t2.STUDENT_YEAR
  FROM SIS_COURSE_DESCRIPTION t0
  JOIN SIS_DEPARTMENT t1 ON t0.DEPARTMENT = t1.DEPARTMENT_CODE
  JOIN MIT_STUDENT_DIRECTORY t2 ON t1.DEPARTMENT_CODE = t2.DEPARTMENT
  WHERE t1.DEPARTMENT_NAME = 'Electrical Eng & Computer Sci'
),
year_counts AS (
  SELECT COURSE_LEVEL,
         STUDENT_YEAR,
         ROW_NUMBER() OVER (PARTITION BY COURSE_LEVEL ORDER BY COUNT(*) DESC) AS rn
  FROM subq2
  GROUP BY COURSE_LEVEL, STUDENT_YEAR
)
SELECT s1.DEPARTMENT_NAME,
       s1.max_total_units,
       s1.SCHOOL_NAME,
       s2.FULL_NAME,
       s2.EMAIL_ADDRESS,
       s2.COURSE_DESCRIPTION,
       s2.COURSE_LEVEL,
       yc.STUDENT_YEAR AS most_common_student_year
FROM subq1 s1
JOIN subq2 s2 ON s1.DEPARTMENT_NAME = s2.DEPARTMENT_NAME
JOIN year_counts yc ON s2.COURSE_LEVEL = yc.COURSE_LEVEL AND yc.rn = 1