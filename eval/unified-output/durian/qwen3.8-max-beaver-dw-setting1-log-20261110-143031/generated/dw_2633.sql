WITH DeptStats AS (
    SELECT
        ss.DEPARTMENT_NAME,
        ss.SCHOOL_NAME,
        at.TERM_START_DATE,
        MAX(ss.SUBJECT_ENROLLMENT_NUMBER) AS max_enrollment
    FROM SUBJECT_SUMMARY ss
    JOIN ACADEMIC_TERMS at ON ss.TERM_CODE = at.TERM_CODE
    JOIN ACADEMIC_TERM_PARAMETER atp ON at.TERM_CODE = atp.TERM_CODE
    WHERE atp.IS_CURRENT_TERM = 'Y'
    GROUP BY ss.DEPARTMENT_NAME, ss.SCHOOL_NAME, at.TERM_START_DATE
    HAVING MAX(ss.SUBJECT_ENROLLMENT_NUMBER) > 5
)
SELECT DEPARTMENT_NAME, SCHOOL_NAME, TERM_START_DATE, max_enrollment
FROM DeptStats
UNION ALL
SELECT NULL AS DEPARTMENT_NAME, SCHOOL_NAME, NULL AS TERM_START_DATE, SUM(max_enrollment) AS max_enrollment
FROM DeptStats
GROUP BY SCHOOL_NAME
ORDER BY SCHOOL_NAME, DEPARTMENT_NAME