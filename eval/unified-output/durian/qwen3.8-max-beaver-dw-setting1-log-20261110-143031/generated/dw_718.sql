SELECT
  ata.ACADEMIC_YEAR,
  ata.ACADEMIC_YEAR_DESC,
  STDDEV(ccso.TOTAL_UNITS) / AVG(ccso.TOTAL_UNITS) AS coefficient_of_variation_total_units,
  MAX(tso.NUM_ENROLLED_STUDENTS) - MIN(tso.NUM_ENROLLED_STUDENTS) AS enrollment_range,
  VARIANCE(tso.NUM_ENROLLED_STUDENTS) AS enrollment_variance
FROM ACADEMIC_TERMS_ALL ata
JOIN COURSE_CATALOG_SUBJECT_OFFERED ccso ON ata.TERM_CODE = ccso.TERM_CODE
JOIN SUBJECT_OFFERED so ON ccso.TERM_CODE = so.TERM_CODE
JOIN ACADEMIC_TERMS at ON ccso.TERM_CODE = at.TERM_CODE
JOIN TIP_SUBJECT_OFFERED tso ON at.TERM_CODE = tso.TERM_CODE
WHERE ccso.DEPARTMENT_NAME = 'Mathematics'
  AND ccso.IS_OFFERED_FALL_TERM = 'Y'
  AND ccso.TOTAL_UNITS > 0
  AND tso.NUM_ENROLLED_STUDENTS > 0
GROUP BY ata.ACADEMIC_YEAR, ata.ACADEMIC_YEAR_DESC
ORDER BY ata.ACADEMIC_YEAR