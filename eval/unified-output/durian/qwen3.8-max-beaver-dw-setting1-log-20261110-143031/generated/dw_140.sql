SELECT c.DEPARTMENT_NAME,
       t.ACADEMIC_YEAR,
       COUNT(DISTINCT s.SUBJECT_ID) AS num_unique_subjects,
       MIN(s.TOTAL_UNITS) AS min_total_units,
       MAX(t.TERM_END_DATE) AS latest_term_end_date
FROM COURSE_CATALOG_SUBJECT_OFFERED c
JOIN ACADEMIC_TERMS t ON c.EFFECTIVE_TERM_CODE = t.TERM_CODE
JOIN SUBJECT_SUMMARY s ON t.TERM_CODE = s.TERM_CODE AND c.DEPARTMENT_NAME = s.DEPARTMENT_NAME
WHERE s.SUBJECT_ENROLLMENT_NUMBER > 10
  AND c.DEPARTMENT_NAME = 'Mathematics'
GROUP BY c.DEPARTMENT_NAME, t.ACADEMIC_YEAR
ORDER BY c.DEPARTMENT_NAME, t.ACADEMIC_YEAR