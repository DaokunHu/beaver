SELECT
  m.MASTER_DEPT_HIER_LEVEL_2_NAME,
  f.ORGANIZATION_NAME,
  COUNT(f.FCLT_ORGANIZATION_KEY) AS num_organizations,
  MIN(f.ORGANIZATION_NUMBER) AS min_organization_number,
  EXP(AVG(LN(CASE WHEN u.NUM_OF_SUPERVISEES > 0 THEN u.NUM_OF_SUPERVISEES END))) AS geometric_mean_supervisees,
  SUM(u.RESEARCH_VOLUME) AS total_research_volume
FROM FCLT_ORGANIZATION f
JOIN MASTER_DEPT_HIERARCHY m ON f.DLC_KEY = m.DLC_KEY
JOIN SPACE_UNIT s ON f.DLC_KEY = s.DLC_KEY
JOIN SPACE_SUPERVISOR_USAGE u ON u.DEPT_NAMES = s.DLC_KEY
WHERE f.ASSIGNABLE = 1
GROUP BY m.MASTER_DEPT_HIER_LEVEL_2_NAME, f.ORGANIZATION_NAME
ORDER BY num_organizations DESC, geometric_mean_supervisees DESC, total_research_volume DESC