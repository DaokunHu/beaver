WITH Subjects2024_12Units AS (
  SELECT t0.SUBJECT_CODE,
         t0.SUBJECT_NUMBER,
         t0.SUBJECT_TITLE,
         t0.DEPARTMENT_NAME,
         t1.TERM_DESCRIPTION,
         RANK() OVER (PARTITION BY t0.DEPARTMENT_NAME ORDER BY t0.SUBJECT_CODE) AS window_column
  FROM COURSE_CATALOG_SUBJECT_OFFERED t0
  JOIN ACADEMIC_TERMS t1 ON t0.EFFECTIVE_TERM_CODE = t1.TERM_CODE
  JOIN SUBJECT_SUMMARY t2 ON t1.TERM_CODE = t2.TERM_CODE
  WHERE t0.ACADEMIC_YEAR = 2024
    AND t0.TOTAL_UNITS = 12
),
DeptStats AS (
  SELECT tso.OFFER_DEPT_NAME,
         AVG(sos.TOTAL_UNITS) AS avg_total_units,
         MAX(sos.TOTAL_UNITS) - MIN(sos.TOTAL_UNITS) AS range_total_units,
         VARIANCE(sos.TOTAL_UNITS) AS variance_total_units
  FROM TIP_SUBJECT_OFFERED tso
  JOIN TIP_DETAIL td ON tso.SUBJECT_ID = td.SUBJECT_ID
  JOIN SUBJECT_OFFERED_SUMMARY sos ON td.SUBJECT_ID = sos.SUBJECT_ID
  WHERE td.TIP_MATERIAL_STATUS_KEY = 'RQ'
    AND tso.NUM_ENROLLED_STUDENTS >= 1
  GROUP BY tso.OFFER_DEPT_NAME
)
SELECT s.SUBJECT_CODE,
       s.SUBJECT_NUMBER,
       s.SUBJECT_TITLE,
       s.DEPARTMENT_NAME,
       s.TERM_DESCRIPTION,
       s.window_column,
       d.avg_total_units,
       d.range_total_units,
       d.variance_total_units
FROM Subjects2024_12Units s
LEFT JOIN DeptStats d ON s.DEPARTMENT_NAME = d.OFFER_DEPT_NAME
ORDER BY s.DEPARTMENT_NAME, s.SUBJECT_CODE