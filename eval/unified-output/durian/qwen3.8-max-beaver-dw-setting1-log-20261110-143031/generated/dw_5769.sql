SELECT MIN(at.ACADEMIC_YEAR) AS min_academic_year,
       SUM(ccso.TOTAL_UNITS) AS sum_total_units
FROM LIBRARY_RESERVE_MATRL_DETAIL lrm
JOIN ACADEMIC_TERMS at ON lrm.TERM_CODE = at.TERM_CODE
JOIN COURSE_CATALOG_SUBJECT_OFFERED ccso ON at.TERM_CODE = ccso.TERM_CODE
WHERE lrm.LIBRARY_MATERIAL_STATUS_KEY = 'U'
  AND ccso.IS_OFFERED_FALL_TERM = 'Y'
  AND ccso.DEPARTMENT_NAME = 'Mathematics'