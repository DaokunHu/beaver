"""ReAct Agent — unified Agent class.

Driven by the agents.json configuration: each agent entry provides the tool list,
max_turns, and the prompt file (under prompts/) used as the system prompt.

Architecture notes:
- Shared dependencies (ContextVar, registry, config management) live in common.py to break circular dependencies
- Hooks trimmed to the 3 actually used (on_step_start, on_reasoning, on_final_answer)
"""

from __future__ import annotations

import json
import logging
from decimal import Decimal
from typing import Any

from openai import OpenAI

logger = logging.getLogger(__name__)

from Agent.common import (
    build_agent_tools,
    build_llm_log_path,
    get_current_context,
    get_tool_handler,
    load_agents_config,
    load_prompt,
)
from LLM import (
    LLMConfig,
    safe_json_loads,
    stream_chat_completion,
)

__all__ = ["ReActAgent"]


# ──────────────────────────────────────────────
# ReAct base class
# ──────────────────────────────────────────────


class ReActAgent:
    """Unified ReAct Agent driven by agents.json."""

    def __init__(self, client: OpenAI, llm_config: LLMConfig, agent_key: str) -> None:
        self.client = client
        self.llm_config = llm_config
        self.agent_key = agent_key

        agents_cfg = load_agents_config()
        cfg = agents_cfg.get(agent_key, {})
        self.agent_name = cfg.get("name", agent_key)
        self.max_steps = int(cfg.get("max_turns", llm_config.max_steps))

        self.system_prompt = self._load_system_prompt(cfg, agent_key)
        # LLM log path: generated by the Agent layer itself (named after AgentContext.session_id)
        ctx = get_current_context()
        self._log_rendered_path = build_llm_log_path(ctx.session_id if ctx else "")

    # ── Config-driven methods ──

    def _load_system_prompt(self, cfg: dict[str, Any], agent_key: str | None = None) -> str:
        """Load the agent's system prompt.

        Resolution order:
        1. The first entry of prompt_stages in agents.json (an md file name under prompts/)
        2. prompts/{agent_key}.md
        3. A generic fallback prompt
        """
        key = agent_key or self.agent_key
        name = cfg.get("name", key)
        raw_stages = cfg.get("prompt_stages") or []

        if isinstance(raw_stages, list) and raw_stages:
            file_name = str(raw_stages[0]).strip()
            if file_name:
                text = load_prompt(file_name).strip()
                if text:
                    return text
                logger.warning(
                    "prompt file does not exist or is empty: %s (agent=%s), falling back.",
                    file_name, key,
                )

        template = load_prompt(f"{key}.md")
        if template:
            return template.strip()

        return f"You are an intelligent assistant: {name}"

    def _tool_schemas(self) -> list[dict[str, Any]]:
        """Build the tool set from the agent's configured tool names."""
        return build_agent_tools(self.agent_key)

    def _execute_tool_call(self, tool_name: str, raw_arguments: str) -> dict[str, Any]:
        """Tool dispatch: look the tool up in the global registry."""
        handler = get_tool_handler(tool_name)
        if handler is not None:
            return handler(raw_arguments)
        return {"ok": False, "error": f"Unknown tool: {tool_name}"}

    # ── Hooks (overridable by subclasses) ──

    def on_step_start(self, step: int) -> None:
        pass

    def on_reasoning(self, content: str) -> None:
        pass

    def on_final_answer(self, step: int, answer: str) -> None:
        pass

    # ── JSON serialization helpers ──

    @staticmethod
    def _json_default(value: Any) -> Any:
        if isinstance(value, Decimal):
            if value == value.to_integral_value():
                return int(value)
            return float(value)
        raise TypeError(f"Object of type {value.__class__.__name__} is not JSON serializable")

    def _to_json(self, data: Any) -> str:
        return json.dumps(data, ensure_ascii=False, default=self._json_default)

    # ── Streaming LLM invocation ──

    def _call_llm(self, request_payload: dict[str, Any]) -> tuple[str, list[dict[str, Any]], Any]:
        """Call the LLM with streaming (delegated to LLM.stream) and return the result."""
        result = stream_chat_completion(
            self.client,
            request_payload,
            log_rendered_path=getattr(self, "_log_rendered_path", None),
        )

        if result.error:
            return result.error, [], None

        return result.content, result.tool_calls, result.msg

    # ── Core run loop ──

    def run(self, user_task: str, messages: list[dict[str, Any]] | None = None, append_user: bool = True) -> str:
        """Run the ReAct loop."""
        if messages is not None:
            msgs: list[dict[str, Any]] = list(messages)
            if append_user:
                msgs.append({"role": "user", "content": user_task})
        else:
            init_system = {"role": "system", "content": self.system_prompt}
            init_user = {"role": "user", "content": user_task}
            msgs = [init_system, init_user]

        for step in range(1, self.max_steps + 1):
            self.on_step_start(step)

            request_payload: dict[str, Any] = {
                "model": self.llm_config.model,
                "messages": msgs,
                "tools": self._tool_schemas(),
                "tool_choice": "auto",
                "temperature": self.llm_config.temperature,
                "reasoning_effort": self.llm_config.reasoning_effort,
                "extra_body": {
                    "enable_thinking": self.llm_config.enable_thinking,
                    "clear_thinking": self.llm_config.clear_thinking,
                },
            }

            content, tool_calls, msg = self._call_llm(request_payload)

            if not tool_calls:
                answer = content or ""
                if msg and msg.reasoning_content:
                    self.on_reasoning(msg.reasoning_content)
                self.on_final_answer(step, answer)
                assistant_msg: dict[str, Any] = {"role": "assistant", "content": answer}
                if msg and msg.reasoning_content:
                    assistant_msg["reasoning"] = msg.reasoning_content
                msgs.append(assistant_msg)

                self._final_msgs = msgs
                return answer

            parse_failed = False
            for tc in tool_calls:
                try:
                    safe_json_loads(tc["function"]["arguments"])
                except (json.JSONDecodeError, ValueError):
                    parse_failed = True
                    break

            if parse_failed:
                continue

            if msg and msg.reasoning_content:
                self.on_reasoning(msg.reasoning_content)

            message_payload: dict[str, Any] = {"role": "assistant"}
            if content:
                message_payload["content"] = content
            if msg and msg.reasoning_content:
                message_payload["reasoning"] = msg.reasoning_content
            message_payload["tool_calls"] = [
                {
                    "id": tc["id"],
                    "type": "function",
                    "function": {
                        "name": tc["function"]["name"],
                        "arguments": tc["function"]["arguments"],
                    },
                }
                for tc in tool_calls
            ]

            self._execute_tools(tool_calls, msgs, message_payload)

        raise RuntimeError(
            f"Agent '{self.agent_key}' reached the max_steps limit ({self.max_steps}) "
            f"without producing a final answer."
        )

    def _execute_tools(
        self,
        tool_calls: list[dict[str, Any]],
        msgs: list[dict[str, Any]],
        assistant_msg: dict[str, Any],
    ) -> None:
        """Execute all tool_calls of this round serially, then append the assistant + tool results to the context at once."""
        results_by_id: dict[str, dict[str, Any]] = {}

        for tc in tool_calls:
            results_by_id[tc["id"]] = self._run_one_tool(tc)

        msgs.append(assistant_msg)

        for tc in tool_calls:
            tool_msg: dict[str, Any] = {
                "role": "tool",
                "tool_call_id": tc["id"],
                "name": tc["function"]["name"],
                "content": self._to_json(results_by_id[tc["id"]]),
            }
            msgs.append(tool_msg)

    def _run_one_tool(self, tc: dict[str, Any]) -> dict[str, Any]:
        """Execute a single tool call and return the result dict."""
        tool_name = tc["function"]["name"]
        raw_args = tc["function"]["arguments"] or "{}"
        try:
            return self._execute_tool_call(tool_name=tool_name, raw_arguments=raw_args)
        except (ValueError, KeyError, TypeError, AttributeError, json.JSONDecodeError) as e:
            return {"ok": False, "error": str(e)}
